/**
 * Prepare + document + (on consent) apply the handler wiring.
 * Returns { status, docPath?, registryFile?, autoCount, manualCount, plan }.
 *   status: 'no-actions' | 'manual-only' | 'declined' | 'declined-noninteractive'
 *         | 'applied' | 'skipped' | 'failed'
 */
async function wireHandlers(appRoot, opts = {}) {
  const {
    manifest,
    evidence = {},
    wiring = {},
    colors = {},
    assumeYes = false,
    noWire = false,
    quiet = false,
    framework = 'web',
    appName,
    registryExt: registryExtOpt,
    esm: esmOpt,
    ts: tsOpt,
    runTest = false,
    revertOnFailure = true,
    testRunner = null,
    corrector = null,
    files = [],
    maxAttempts = 3,
  } = opts;
  const { blue, cyan, dim, reset } = colors;
  const tag = `${cyan || ''}◉${reset || ''} ${blue || ''}Fiodos${reset || ''}`;

  if (noWire) return { status: 'skipped' };
  const actions = (manifest && manifest.actions) || [];
  if (!actions.length) return { status: 'no-actions' };

  const fyodosDirRel = resolveFiodosDirRel(appRoot);
  const fyodosDirAbs = path.join(appRoot, fyodosDirRel);
  const detected = detectTsEsm(appRoot);
  const ts = tsOpt != null ? tsOpt : detected.ts;
  const esm = esmOpt != null ? esmOpt : detected.esm;
  const ext = registryExtOpt || (ts ? '.ts' : esm ? '.js' : '.cjs');

  const plan = prepareHandlerPlan({ appRoot, manifest, evidence, wiring, fyodosDirRel });
  const hasBridge = plan.auto.some((e) => e.kind === 'bridge');
  const componentEdits = planComponentEdits(appRoot, plan, { ts });
  const registryRel = path.join(fyodosDirRel, `${REGISTRY_BASENAME}${ext}`).split(path.sep).join('/');
  const bridgeRel = path.join(fyodosDirRel, `${BRIDGE_BASENAME}${ext}`).split(path.sep).join('/');
  const registryImport = `./${REGISTRY_BASENAME}`;

  const mountSnippet =
    `import { ${REGISTRY_EXPORT} } from '${registryImport}';\n` +
    `\n` +
    `<FiodosAgent\n` +
    `  apiKey={/* your API key */}\n` +
    `  registries={${REGISTRY_EXPORT}}\n` +
    `/>`;

  // 1) ALWAYS write the document first, so the developer can read before consenting.
  fs.mkdirSync(fyodosDirAbs, { recursive: true });
  const docAbs = path.join(fyodosDirAbs, DOC_BASENAME);
  const docText = buildHandlerDoc(plan, {
    appName: appName || path.basename(appRoot),
    framework,
    registryRel,
    bridgeRel,
    edits: componentEdits,
    mountSnippet,
  });
  fs.writeFileSync(docAbs, docText);
  const docRel = path.relative(appRoot, docAbs);

  // 2) Nothing can be wired with confidence → leave the doc, explain, never guess.
  //    BUT when an auto-corrector is available the initial plan being empty is not
  //    terminal: the loop will re-prompt the AI to FIX each action, so we proceed
  //    to consent and let the loop decide what ends up wired.
  const loopEnabled = typeof corrector === 'function' && runTest && testRunner;
  if (!plan.auto.length && !loopEnabled) {
    if (!quiet) {
      console.error(
        `\n${tag} · ${dim || ''}Prepared the action wiring, but none of the ` +
          `${plan.manual.length} action(s) can be connected with confidence.${reset || ''}`,
      );
      console.error(
        `${tag} · See what is needed and how to do it by hand in: ${docRel}`,
      );
    }
    return { status: 'manual-only', docPath: docAbs, autoCount: 0, manualCount: plan.manual.length, plan };
  }

  // 3) Second, separate confirmation (after the orb's), referencing the doc.
  const touchNote = componentEdits.length
    ? ` ${componentEdits.length} file(s) of YOURS will be edited (with reversible markers).`
    : '';
  const prompt =
    `\n${tag} · The action wiring that lets the agent run your functions is ` +
    `ready (${plan.auto.length} automatic, ${plan.manual.length} for review).${touchNote}\n` +
    `${tag} · Review the exact changes that will be made to your code in:\n` +
    `         ${docRel}\n` +
    `${tag} · Apply these changes after reviewing? [yes/no] `;

  if (!assumeYes && !process.stdin.isTTY) {
    if (!quiet) {
      console.error(prompt.trimEnd());
      console.error(
        `${tag} · ${dim || ''}Non-interactive terminal: leaving your code untouched. The document ` +
          `is at ${docRel}. Re-run with --wire-yes to apply it.${reset || ''}`,
      );
    }
    return { status: 'declined-noninteractive', docPath: docAbs, autoCount: plan.auto.length, manualCount: plan.manual.length, plan };
  }

  const yes = assumeYes || (await askYesNo(prompt));
  if (!yes) {
    if (!quiet) {
      console.error(
        `${tag} · ${dim || ''}Leaving your code untouched. The document stays at ${docRel} ` +
          `in case you want to wire it by hand or re-run with --wire-yes.${reset || ''}`,
      );
    }
    return { status: 'declined', docPath: docAbs, autoCount: plan.auto.length, manualCount: plan.manual.length, plan };
  }

  // 4) Baseline: BEFORE touching anything, check whether the app already builds.
  let baseline = null;
  if (runTest && testRunner) {
    if (!quiet) {
      console.error(`${tag} · ${dim || ''}Checking the build baseline BEFORE wiring…${reset || ''}`);
    }
    try {
      baseline = await testRunner(appRoot, { framework });
    } catch (err) {
      baseline = { ok: false, stage: 'runner', output: err && err.message };
    }
  }

  const registryAbs = path.join(fyodosDirAbs, `${REGISTRY_BASENAME}${ext}`);
  const bridgeAbs = path.join(fyodosDirAbs, `${BRIDGE_BASENAME}${ext}`);

  // 4b) AUTO-CORRECTION LOOP. When a corrector (AI re-prompt) is available we run
  //     the verify→diagnose→correct→retry loop per action. Only actions that PASS
  //     verification are written; the rest are reverted and reported honestly.
  if (corrector && runTest && testRunner) {
    const wiringMap = { ...wiring };
    const loop = await runAutoCorrectionLoop({
      appRoot, fyodosDirRel, fyodosDirAbs, manifest, evidence, wiringMap,
      ts, esm, ext, testRunner, corrector, files, framework, maxAttempts,
      tag, dim, reset, registryRel, baseline, quiet,
    });

    const finalAuto = loop.ready;
    const droppedReview = loop.dropped.map((d) => ({
      ...d,
      confidence: 'review',
      reason: `could not be wired automatically after ${d.attempts} attempt(s): ${d.reason}`,
    }));
    const finalPlan = {
      auto: finalAuto, review: droppedReview, manual: droppedReview,
      entries: [...finalAuto, ...droppedReview],
    };
    const finalEdits = planComponentEdits(appRoot, finalPlan, { ts });
    const finalHasBridge = finalAuto.some((e) => e.kind === 'bridge');

    // Rewrite the doc with the REAL verification results (attempts, levels, drops).
    fs.writeFileSync(docAbs, buildHandlerDoc(finalPlan, {
      appName: appName || path.basename(appRoot),
      framework, registryRel, bridgeRel, edits: finalEdits, mountSnippet,
      verification: loop.attemptsLog,
    }));

    if (!finalAuto.length) {
      return {
        status: 'manual-only', docPath: docAbs, autoCount: 0,
        manualCount: droppedReview.length, plan: finalPlan,
        verification: loop.attemptsLog, dropped: loop.dropped, baseline,
      };
    }

    const generatedFiles = [registryAbs];
    let backups = [];
    try {
      if (finalHasBridge) {
        fs.writeFileSync(bridgeAbs, buildBridgeModule({ ts, esm }));
        generatedFiles.push(bridgeAbs);
      }
      fs.writeFileSync(registryAbs, buildRegistryModule(finalPlan, { ts, esm }));
      ({ backups } = applyComponentEdits(appRoot, finalEdits));
    } catch (err) {
      revertAll(backups, generatedFiles);
      return { status: 'failed', docPath: docAbs, error: err, plan: finalPlan, verification: loop.attemptsLog };
    }

    // Final combined build (each action passed in isolation; confirm the union).
    const touchedForReg = () => [...finalEdits.map((e) => e.file), 'handlers.generated', 'bridge'];
    const runBuild = async () => {
      try {
        return await testRunner(appRoot, { framework });
      } catch (err) {
        return { ok: false, stage: 'runner', output: err && err.message };
      }
    };
    let test = await runBuild();
    let reg = compileRegressed((baseline && baseline.output) || '', (test && test.output) || '', touchedForReg());
    let combinedRegression = !reg.ok && baseline && baseline.ok;

    // PARTIAL DEGRADATION: if the union regressed, don't nuke the whole batch.
    // Attribute the NEW errors to the specific entries that caused them, revert
    // only those, and rebuild once with the survivors. The dev loses the
    // problematic action(s), never the rest. We attribute on the full error set
    // (real + lint): a non-zero build is unacceptable to ship regardless of the
    // cause, but we record WHY each culprit fell (broken code vs. a style rule
    // our fence could not silence) for an honest report.
    let degraded = null;
    if (combinedRegression && revertOnFailure) {
      const culprits = attributeCulprits(finalAuto, reg.newErrors);
      const survivors = finalAuto.filter((e) => !culprits.has(e.intent));
      if (culprits.size && survivors.length && survivors.length < finalAuto.length) {
        const { real, lint } = classifyErrorLines(reg.newErrors);
        const culpritEntries = finalAuto.filter((e) => culprits.has(e.intent));
        // Revert everything, then re-apply ONLY the survivors and rebuild once.
        revertAll(backups, generatedFiles);
        const survivorPlan = { auto: survivors, review: droppedReview, manual: droppedReview, entries: [...survivors, ...droppedReview] };
        const survivorEdits = planComponentEdits(appRoot, survivorPlan, { ts });
        const survivorHasBridge = survivors.some((e) => e.kind === 'bridge');
        const survivorGenerated = [registryAbs];
        let survivorBackups = [];
        try {
          if (survivorHasBridge) {
            fs.writeFileSync(bridgeAbs, buildBridgeModule({ ts, esm }));
            survivorGenerated.push(bridgeAbs);
          }
          fs.writeFileSync(registryAbs, buildRegistryModule(survivorPlan, { ts, esm }));
          ({ backups: survivorBackups } = applyComponentEdits(appRoot, survivorEdits));
        } catch (err) {
          revertAll(survivorBackups, survivorGenerated);
          return { status: 'failed', docPath: docAbs, error: err, plan: finalPlan, verification: loop.attemptsLog };
        }
        const survivorTest = await runBuild();
        const survivorReg = compileRegressed((baseline && baseline.output) || '', (survivorTest && survivorTest.output) || '', [...survivorEdits.map((e) => e.file), 'handlers.generated', 'bridge']);
        if (survivorReg.ok || !(baseline && baseline.ok)) {
          // Survivors build clean → keep them; report the dropped culprits.
          degraded = culpritEntries.map((e) => ({
            ...e, confidence: 'review',
            reason: `wired clean in isolation but broke the combined build${lint.length && !real.length ? ' (project style rule our fence could not silence)' : ''}; reverted to keep the rest building`,
          }));
          const mergedReview = [...droppedReview, ...degraded];
          const keptPlan = { auto: survivors, review: mergedReview, manual: mergedReview, entries: [...survivors, ...mergedReview] };
          fs.writeFileSync(docAbs, buildHandlerDoc(keptPlan, {
            appName: appName || path.basename(appRoot),
            framework, registryRel, bridgeRel, edits: survivorEdits, mountSnippet,
            verification: loop.attemptsLog,
          }));
          return {
            status: 'applied', partial: true, docPath: docAbs, registryFile: registryAbs, registryRel,
            bridgeFile: survivorHasBridge ? bridgeAbs : null, mountSnippet,
            autoCount: survivors.length, manualCount: mergedReview.length,
            editedFiles: survivorEdits.map((e) => e.file), plan: keptPlan,
            verification: loop.attemptsLog, dropped: [...loop.dropped, ...degraded],
            degraded, baseline, test: survivorTest,
            preexistingFailure: baseline && baseline.ok === false && baseline.stage !== 'skipped-no-deps',
          };
        }
        // Even the survivors regressed → fall through to a full revert (already reverted).
        revertAll(survivorBackups, survivorGenerated);
        return {
          status: 'reverted', docPath: docAbs, plan: finalPlan, test: survivorTest,
          verification: loop.attemptsLog, dropped: loop.dropped, baseline,
        };
      }
      // Could not isolate a culprit → conservative full revert.
      revertAll(backups, generatedFiles);
      return {
        status: 'reverted', docPath: docAbs, plan: finalPlan, test,
        verification: loop.attemptsLog, dropped: loop.dropped, baseline,
      };
    }
    return {
      status: reg.ok ? 'applied' : 'applied-untested',
      docPath: docAbs, registryFile: registryAbs, registryRel,
      bridgeFile: finalHasBridge ? bridgeAbs : null, mountSnippet,
      autoCount: finalAuto.length, manualCount: droppedReview.length,
      editedFiles: finalEdits.map((e) => e.file), plan: finalPlan,
      verification: loop.attemptsLog, dropped: loop.dropped,
      baseline, test, preexistingFailure: baseline && baseline.ok === false && baseline.stage !== 'skipped-no-deps',
    };
  }

  // 5) Apply (single-shot path, no corrector): bridge module (if any) + registry +
  //    the edits inside the user's own components. Everything idempotent; component
  //    files are snapshotted so we can revert cleanly if the post-wiring test fails.
  const generatedFiles = [registryAbs];
  let backups = [];
  try {
    if (hasBridge) {
      fs.writeFileSync(bridgeAbs, buildBridgeModule({ ts, esm }));
      generatedFiles.push(bridgeAbs);
    }
    fs.writeFileSync(registryAbs, buildRegistryModule(plan, { ts, esm }));
    if (!fs.readFileSync(registryAbs, 'utf8').includes(GENERATED_MARKER)) {
      throw new Error('post-write verification failed');
    }
    ({ backups } = applyComponentEdits(appRoot, componentEdits));
  } catch (err) {
    revertAll(backups, generatedFiles);
    return { status: 'failed', docPath: docAbs, error: err, plan };
  }

  const baseResult = {
    docPath: docAbs,
    registryFile: registryAbs,
    registryRel,
    bridgeFile: hasBridge ? bridgeAbs : null,
    mountSnippet,
    autoCount: plan.auto.length,
    manualCount: plan.manual.length,
    editedFiles: componentEdits.map((e) => e.file),
    baseline,
    plan,
  };

  // 6) Post-wiring test: make sure WE did not break the app. We only revert when
  //    the app built BEFORE and fails AFTER (a regression we caused). If it was
  //    already broken, we keep the wiring and flag it (can't verify via build).
  if (runTest && testRunner) {
    if (baseline && baseline.ok === false && baseline.stage !== 'skipped-no-deps') {
      return { status: 'applied-untested', ...baseResult, test: baseline, preexistingFailure: true };
    }
    if (!quiet) {
      console.error(`${tag} · ${dim || ''}Checking the app still builds after wiring…${reset || ''}`);
    }
    let test;
    try {
      test = await testRunner(appRoot, { framework });
    } catch (err) {
      test = { ok: false, stage: 'runner', output: err && err.message };
    }
    // Regression we caused: built before, fails now → revert.
    if (!test.ok && baseline && baseline.ok && revertOnFailure) {
      revertAll(backups, generatedFiles);
      return { status: 'reverted', ...baseResult, test };
    }
    return { status: test.ok ? 'applied' : 'applied-untested', ...baseResult, test };
  }

  return { status: 'applied', ...baseResult };
}

function reportHandlerResult(result, colors = {}, opts = {}) {
  const quiet = opts.quiet !== false;
  if (!result) return;
  const { blue, cyan, dim, reset } = colors;
  const tag = `${cyan || ''}◉${reset || ''} ${blue || ''}Fiodos${reset || ''}`;
  switch (result.status) {
    case 'applied':
    case 'applied-untested':
      if (result.partial && Array.isArray(result.degraded) && result.degraded.length) {
        // Partial degradation: most actions are wired; only the few that broke the
        // combined build were rolled back so the rest (and the build) stay green.
        const names = result.degraded.map((d) => `'${d.intent}'`).join(', ');
        console.error(`${tag} · ${dim || ''}Wired ${result.autoCount} action(s). ${result.degraded.length} (${names}) wired clean alone but broke the combined build, so only those were reverted — the rest are live. See the document to apply them by hand.${reset || ''}`);
        return;
      }
      if (quiet) return;
      break;
    case 'reverted':
      // Not a fatal error: the manifest is published and the orb + link actions
      // work. Only the OPTIONAL in-code wiring for function actions was rolled
      // back because the project's build did not pass with it — so we leave the
      // code untouched and document how to wire it by hand. Keep the tone calm.
      console.error(`${tag} · ${dim || ''}Voice actions are published and the orb is live. The optional in-code wiring for function actions was skipped (your build didn't pass with it), so your code was left untouched — see the document to apply it by hand.${reset || ''}`);
      break;
    case 'manual-only':
      if (quiet) return;
      console.error(`${tag} · ${dim || ''}Wiring documented; apply it by hand following ${result.docPath}.${reset || ''}`);
      break;
    case 'declined':
    case 'declined-noninteractive':
      break;
    case 'failed':
      console.error(`${tag} · ✗ Could not write the handler registry: ${result.error && result.error.message}`);
      break;
    case 'no-actions':
    case 'skipped':
    default:
      break;
  }
}

