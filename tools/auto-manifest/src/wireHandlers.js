function relImport(fromDirRel, toFileRel) {
  let rel = path.relative(fromDirRel, normRel(toFileRel)).split(path.sep).join('/');
  rel = rel.replace(/\.(t|j)sx?$/, '');
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

/**
 * Turn the AI's proposed wiring for ONE action into a verified `auto` entry, or
 * return { reason } when the proposal cannot be safely trusted. This is the
 * heart of the new model: the AI proposes (imports + a call expression read
 * straight from the user's code) and the verifier confirms every symbol exists
 * and every identifier the call reads is either imported or a safe global.
 */
function buildAiEntry({ appRoot, fyodosDirRel, base, aiW, manifestParams }) {
  if (!aiW || typeof aiW !== 'object') return { reason: 'the AI proposed no wiring for this action' };
  if (aiW.strategy === 'bridge') {
    return buildAiBridgeEntry({ appRoot, fyodosDirRel, base, aiW });
  }
  if (aiW.strategy && aiW.strategy !== 'module') {
    return { reason: `unknown wiring strategy: '${aiW.strategy}'` };
  }

  const call = String(aiW.call || '').trim();
  if (!call) return { reason: 'the AI did not provide a verifiable call expression' };

  const rawImports = Array.isArray(aiW.imports) ? aiW.imports : [];
  // 1) Every required symbol must really exist where the AI says it does.
  const required = Array.isArray(aiW.requiredSymbols) ? aiW.requiredSymbols : [];
  for (const r of required) {
    if (!fileHasSymbol(appRoot, r && r.file, r && r.name)) {
      return {
        reason: `the verifier did not find symbol '${r && r.name}' in '${normRel(r && r.file)}' (the AI proposed it but it does not exist in the code)`,
      };
    }
  }

  // 2) Build verified imports. Each imported file+name must exist on disk.
  const imports = [];
  const importedNames = new Set();
  for (const imp of rawImports) {
    const name = String((imp && imp.name) || '').trim();
    const rawFrom = normRel(imp && imp.from);
    const kind = (imp && imp.kind) || 'named';
    if (!name || !rawFrom) return { reason: 'an import proposed by the AI is incomplete (missing name/from)' };
    const from = resolveSourceFile(appRoot, rawFrom);
    if (!from) {
      return { reason: `the proposed import points to a non-existent file: '${rawFrom}'` };
    }
    // For named imports the symbol must be present in that file; default/namespace
    // bind the module's default/whole export so only file existence is checked.
    if (kind === 'named' && !fileHasSymbol(appRoot, from, name)) {
      return { reason: `named import '${name}' does not exist in '${from}'` };
    }
    imports.push({ kind, name, importPath: relImport(fyodosDirRel, from) });
    importedNames.add(name);
  }

  // 3) Reject the "detached instance" anti-pattern (new Service() + mutate).
  const detached = detachedInstanceReceiver(call);
  if (detached) {
    return {
      reason:
        `the expression instantiates '${detached}' with 'new' and uses it as the receiver; ` +
        'if it is an injected service/state (DI) or a singleton, that new instance ' +
        'is disconnected from the one the UI sees and the action would have no observable effect. ' +
        'It needs a bridge to the real singleton instead of instantiating it.',
    };
  }

  // 4) Safety: every free identifier the call reads must be imported, a locally
  //    declared binding, or a safe global. Anything else fails closed (→ review).
  const locals = declaredLocals(call);
  for (const id of freeIdentifiers(call)) {
    if (JS_KEYWORDS.has(id) || importedNames.has(id) || SAFE_GLOBALS.has(id) || locals.has(id)) continue;
    return {
      reason: `the proposed call references '${id}', which could not be verified in your code — wire this action manually`,
    };
  }

  return {
    ...base,
    confidence: 'auto',
    source: 'ai',
    kind: 'ai-call',
    imports,
    callExpr: call,
    usesParams: /\bparams\b/.test(call),
  };
}

/**
 * MECHANICAL ANCHOR RESCUE — the fix for the dominant wiring failure class
 * ("the insertion point in '<file>' is ambiguous / not found").
 *
 * The AI's anchor only needs to locate the RIGHT COMPONENT SCOPE: the actual
 * insertion goes before the nearest JSX `return` (see insertRegisterBlock), so
 * when the AI picks a line that appears several times in a big file we do not
 * have to give up. We derive a deterministic anchor ourselves: the line where
 * one of the identifiers the `invoke` expression CALLS/READS is DECLARED
 * (`const [x, setX] = useState(...)`, `function foo(`, `const foo =`, a class
 * field, …). Declarations are unique per scope in real code, and anchoring on
 * the declaration guarantees the registration lands in the scope where the
 * symbol is visible. Correctness is still gated by the same compile-regression
 * + effect-probe verification as every other wiring — this only replaces the
 * "reject" with a better, mechanical candidate.
 */
function deriveBridgeAnchor(content, invoke) {
  const src = stripLiterals(String(invoke || ''));
  // Identifiers the invoke CALLS first (most specific), then everything it reads.
  const ordered = [];
  const pushId = (id) => {
    if (!id || id === 'args' || id === 'this') return;
    if (JS_KEYWORDS.has(id) || SAFE_GLOBALS.has(id)) return;
    if (!ordered.includes(id)) ordered.push(id);
  };
  let m;
  const callRe = /(?:^|[^.\w$])([A-Za-z_$][\w$]*)\s*\(/g;
  while ((m = callRe.exec(src))) pushId(m[1]);
  for (const id of freeIdentifiers(invoke)) pushId(id);

  for (const id of ordered) {
    // Full LINES that look like a declaration of `id` in the file.
    const lineRe = new RegExp(
      `^[ \\t]*(?:export\\s+)?(?:const|let|var|function|async\\s+function|private|public|protected|readonly)\\b[^\\n]*(?:^|[^.\\w$])${esc(id)}(?![\\w$])[^\\n]*$`,
      'gm',
    );
    const decls = [];
    while ((m = lineRe.exec(content))) decls.push(m[0]);
    // Exactly ONE declaration line, and that line must be unique as a substring
    // (so indexOf-based insertion is deterministic and idempotent).
    if (decls.length === 1 && countOccurrences(content, decls[0]) === 1) {
      return decls[0];
    }
  }
  return null;
}

/**
 * "Once wired, never regressed": when the file ALREADY contains a generated
 * block registering this intent (from a previous verified run), reuse that
 * position instead of re-rolling the AI's anchor. Re-running the wiring is
 * otherwise nondeterministic — a bad anchor + an unlucky AI correction can
 * un-wire an action that worked yesterday. Returns the nearest line ABOVE the
 * existing block that survives the strip and is unique in the stripped
 * content (a deterministic anchor for the same spot), or null.
 */
function reuseExistingBlockAnchor(rawContent, strippedContent, intent) {
  const blockRe = new RegExp(
    `(${esc(EDIT_START_PREFIX)}[^\\n]*)\\n[\\s\\S]*?${esc(EDIT_END)}`,
    'g',
  );
  let m;
  while ((m = blockRe.exec(rawContent))) {
    if (!GENERATED_HEADER_RE.test(m[1])) continue;
    if (!new RegExp(`"${esc(intent)}"\\s*:`).test(m[0])) continue;
    const lines = rawContent.slice(0, m.index).split('\n');
    for (let i = lines.length - 1; i >= 0; i--) {
      const line = lines[i];
      const t = line.trim();
      if (!t || t.startsWith('//') || t.startsWith('/*') || t.startsWith('*')) continue;
      if (line.includes('FYODOS:')) continue;
      if (countOccurrences(strippedContent, line) === 1) return line;
    }
  }
  return null;
}

/**
 * True when an anchor that appears several times is HARMLESS: every occurrence
 * resolves to the same actual insertion point (the nearest JSX `return`), so
 * the ambiguity cannot change where the registration lands.
 */
function ambiguousAnchorSameInsertion(content, anchor) {
  const points = new Set();
  let idx = content.indexOf(anchor);
  while (idx !== -1) {
    points.add(nearestJsxReturn(content, idx));
    if (points.size > 1) return false;
    idx = content.indexOf(anchor, idx + anchor.length);
  }
  // A single resolved point that exists (-1 = no JSX return found → not safe).
  return points.size === 1 && !points.has(-1);
}

/**
 * Verify the AI's BRIDGE proposal for ONE action. A bridge edits the user's own
 * component (under consent) to register the live, in-scope function/instance so
 * the standalone registry can reach component-local state. The verifier confirms
 * the edit can be applied SAFELY and that nothing is fabricated:
 *   · the component file exists and the anchor resolves to ONE unambiguous
 *     insertion point — when the AI's anchor is missing/ambiguous, a mechanical
 *     anchor is derived from the declaration of the invoked symbol (see
 *     deriveBridgeAnchor) instead of giving up,
 *   · every requiredSymbol exists in the code,
 *   · `invoke` does not create a detached `new Service()` instance,
 *   · every identifier `invoke` reads is `args`/`this`, a safe global, an import
 *     the AI declared (and that resolves), or a symbol that exists in the file.
 * Returns an `auto` entry (kind 'bridge') or { reason } → review.
 */
function buildAiBridgeEntry({ appRoot, fyodosDirRel, base, aiW }) {
  const b = aiW.bridge || {};
  const file = normRel(b.file);
  let anchor = String(b.anchor || '').trim();
  const invoke = String(b.invoke || '').trim();
  const why = aiW.bridgeReason ? ` (${aiW.bridgeReason})` : '';

  if (!file) return { reason: `the AI marked a bridge but did not indicate the component file${why}` };
  const rawContent = readFileSafe(appRoot, file);
  if (rawContent == null) return { reason: `could not read the component '${file}' to apply the bridge` };
  if (!invoke) return { reason: `the AI did not provide the bridge 'invoke' expression for '${file}'` };
  // Anchor decisions must be made on the content the block will ACTUALLY be
  // inserted into: applyComponentEdits strips our previous blocks first. On a
  // re-run over an already-wired file, the old generated block contains the
  // same invoke expressions, so counting occurrences on the raw file falsely
  // flags unique anchors as "ambiguous" and un-wires working actions.
  const content = stripFiodosBlocks(rawContent);

  // Anchor resolution ladder: exact-unique AI anchor → harmless-ambiguous AI
  // anchor → mechanically derived declaration anchor → review. The old behavior
  // (reject on 0/>1 occurrences) left real, wireable actions "manual" whenever
  // the AI picked a repeated line in a big file.
  let anchorDerived = false;
  const occ = anchor ? countOccurrences(content, anchor) : 0;
  if (occ !== 1) {
    const scope = b.scope === 'class-field' ? 'class-field' : 'statement';
    const reused = reuseExistingBlockAnchor(rawContent, content, base.intent);
    if (reused) {
      // A previous run already wired this intent here and verified it; the
      // proven position beats re-rolling an ambiguous AI anchor.
      anchor = reused;
      anchorDerived = true;
    } else if (occ > 1 && scope === 'statement' && ambiguousAnchorSameInsertion(content, anchor)) {
      // Keep the AI anchor: every occurrence lands on the same insertion point.
    } else {
      const derived = deriveBridgeAnchor(content, invoke);
      if (derived) {
        anchor = derived;
        anchorDerived = true;
      } else if (!anchor || occ === 0) {
        return { reason: `no safe insertion point was found in '${file}' — wire this action manually` };
      } else {
        return { reason: `the insertion point in '${file}' is ambiguous — wire this action manually` };
      }
    }
  }

  // requiredSymbols must really exist.
  const required = Array.isArray(aiW.requiredSymbols) ? aiW.requiredSymbols : [];
  for (const r of required) {
    if (!fileHasSymbol(appRoot, r && r.file, r && r.name)) {
      return { reason: `symbol '${r && r.name}' was not found in '${normRel(r && r.file)}' — wire this action manually` };
    }
  }

  // Never create a fresh, detached instance of a service/singleton.
  const detached = detachedInstanceReceiver(invoke);
  if (detached) {
    return {
      reason:
        `the bridge instantiates '${detached}' with 'new' and uses it as the receiver; that creates an ` +
        'instance disconnected from the one the UI sees. It must use the real instance (e.g. this.<service>), not instantiate it.',
    };
  }

  // Verify extra imports the invoke needs.
  const imports = [];
  const importedNames = new Set();
  for (const imp of Array.isArray(b.imports) ? b.imports : []) {
    const name = String((imp && imp.name) || '').trim();
    const rawFrom = normRel(imp && imp.from);
    const kind = (imp && imp.kind) || 'named';
    if (!name || !rawFrom) return { reason: 'a bridge import is incomplete (missing name/from)' };
    // The component often ALREADY imports the symbol (useApp, a store hook…).
    // Re-importing it produces "Duplicate identifier" and fails the candidate,
    // so an already-in-scope name is accepted without adding a second import.
    if (new RegExp(`^\\s*import\\b[^;\\n]*[^\\w$]${esc(name)}[^\\w$][^;\\n]*from`, 'm').test(content)) {
      importedNames.add(name);
      continue;
    }
    const from = resolveSourceFile(appRoot, rawFrom);
    if (!from) return { reason: `the bridge import points to a non-existent file: '${rawFrom}'` };
    if (kind === 'named' && !fileHasSymbol(appRoot, from, name)) return { reason: `named import '${name}' does not exist in '${from}'` };
    imports.push({ kind, name, importPath: relImport(path.dirname(file), from) });
    importedNames.add(name);
  }

  // Safety: identifiers `invoke` reads must be accounted for. Inside a component
  // the scope is rich, so we accept anything that actually appears in the file;
  // truly unknown identifiers (typos, hallucinations) fail closed.
  const locals = declaredLocals(invoke);
  for (const id of freeIdentifiers(invoke)) {
    if (id === 'args' || JS_KEYWORDS.has(id) || SAFE_GLOBALS.has(id) || locals.has(id) || importedNames.has(id)) continue;
    if (fileHasSymbol(appRoot, file, id)) continue;
    return {
      reason: `references '${id}', which is not available in '${file}' — wire this action manually`,
    };
  }

  const bridgeMethod = base.intent;
  const scope = b.scope === 'class-field' ? 'class-field' : 'statement';
  return {
    ...base,
    confidence: 'auto',
    source: 'ai',
    kind: 'bridge',
    bridge: {
      file,
      anchor,
      invoke,
      scope,
      method: bridgeMethod,
      imports,
      importPathToBridge: relImport(path.dirname(file), path.join(fyodosDirRel, BRIDGE_BASENAME)),
    },
    callExpr: `getFiodosBridge()[${JSON.stringify(bridgeMethod)}](params)`,
    usesParams: true,
  };
}

/**
 * Mechanical fallback for ONE action (the original pattern detector), now used
 * only when the AI did not provide usable wiring. Returns an `auto` entry in the
 * unified shape, or { reason }.
 */
function buildMechanicalEntry({ appRoot, fyodosDirRel, base, manifestParams }) {
  const { file: evFile, handler } = base;
  if (!evFile) return { reason: 'the analysis did not provide an evidence file for this action' };
  const absFile = path.join(appRoot, evFile);
  let content = null;
  if (fs.existsSync(absFile)) {
    try {
      content = fs.readFileSync(absFile, 'utf8');
    } catch {
      content = null;
    }
  }
  if (!content) return { reason: `could not read the evidence file '${evFile}'` };

  const exported = findExportedFunction(content, handler);
  const store = exported ? null : findStoreMethod(content, handler);
  if (!exported && !store) {
    return {
      reason: `'${handler}' in '${evFile}' could not be reached safely from a generated module — wire it manually`,
    };
  }

  const targetParams = (exported || store).params;
  const mapped = mapParams(targetParams, manifestParams);
  if (!mapped.ok) return { reason: `signature not safely mappable: ${mapped.reason}` };

  const importPath = relImport(fyodosDirRel, evFile);
  if (exported) {
    const localName = exported.isDefault ? `__fyodos_${handler}` : handler;
    return {
      ...base,
      confidence: 'auto',
      source: 'mechanical',
      kind: 'exported-fn',
      imports: [{ kind: exported.isDefault ? 'default' : 'named', name: localName, importPath }],
      callExpr: `${localName}(${mapped.args.join(', ')})`,
      usesParams: /params\[/.test(mapped.args.join(', ')),
    };
  }
  return {
    ...base,
    confidence: 'auto',
    source: 'mechanical',
    kind: 'store-method',
    imports: [{ kind: 'named', name: store.store, importPath }],
    callExpr: `${store.store}.getState().${handler}(${mapped.args.join(', ')})`,
    usesParams: /params\[/.test(mapped.args.join(', ')),
  };
}

/**
 * Build the wiring plan from the produced manifest + evidence + AI wiring.
 * Source of truth is the AI's per-action wiring (verified); the mechanical
 * detector is only a fallback. Anything still unverified becomes a `review`
 * entry (never wired blindly).
 *
 * @param {object} args
 * @param {string} args.appRoot
 * @param {object} args.manifest
 * @param {object} args.evidence  { actions: { intent: { file, symbol, whatItDoes } } }
 * @param {object} [args.wiring]  { <intent>: { strategy, imports, call, requiredSymbols } }
 * @param {string} args.fyodosDirRel  where the generated registry will live
 */
function prepareHandlerPlan({ appRoot, manifest, evidence, wiring = {}, fyodosDirRel }) {
  const actions = (manifest && manifest.actions) || [];
  const evActions = (evidence && evidence.actions) || {};
  const aiWiring = wiring || {};
  const entries = [];

  for (const action of actions) {
    const intent = action.intent;
    // Link/navigation actions have no handler and need NO wiring — the client
    // performs the navigation in navTarget. Skip them entirely here.
    if (action.kind === 'link') continue;
    const handler = action.handler || intent;
    const ev = evActions[intent] || {};
    const evFile = normRel(ev.file);
    const manifestParams = Object.entries(action.parameters || {}).map(([name, spec]) => ({
      name,
      required: spec && spec.required === true,
    }));

    const base = {
      intent,
      handler,
      label: action.label || intent,
      file: evFile || null,
      symbol: ev.symbol || null,
      whatItDoes: ev.whatItDoes || ev.what || null,
      requireConfirmation: action.requireConfirmation === true,
      voiceConfirmation: action.voiceConfirmation || null,
      idempotencyCheck: action.idempotencyCheck || null,
      manifestParams,
    };

    // 1) AI-proposed wiring (verified). Primary source.
    const aiTry = buildAiEntry({ appRoot, fyodosDirRel, base, aiW: aiWiring[intent], manifestParams });
    if (aiTry.confidence === 'auto') {
      entries.push(aiTry);
      continue;
    }

    // 2) Mechanical fallback (the old pattern detector).
    const mechTry = buildMechanicalEntry({ appRoot, fyodosDirRel, base, manifestParams });
    if (mechTry.confidence === 'auto') {
      entries.push({ ...mechTry, aiReason: aiTry.reason });
      continue;
    }

    // 3) Neither could be verified → needs review, with both reasons.
    entries.push({
      ...base,
      confidence: 'review',
      reason: aiTry.reason || mechTry.reason,
      aiReason: aiTry.reason,
      mechReason: mechTry.reason,
    });
  }

  const auto = entries.filter((e) => e.confidence === 'auto');
  // `manual` retained as an alias for backward-compatible callers/tests.
  const review = entries.filter((e) => e.confidence === 'review');
  return { entries, auto, review, manual: review };
}

// ── Registry codegen (idempotent: regenerated wholesale, clearly marked) ───────

function buildRegistryModule(plan, opts = {}) {
  const ts = opts.ts !== false;
  const esm = opts.esm !== false;
  const hasBridge = plan.auto.some((e) => e.kind === 'bridge');

  // Group MODULE-strategy imports by source path. Bridge entries do NOT import
  // the user's symbols here — they reach them through the bridge holder — so
  // their `imports` belong to the component edit, not the registry.
  const importsByPath = new Map();
  for (const e of plan.auto) {
    if (e.kind === 'bridge') continue;
    for (const imp of e.imports || []) {
      if (!importsByPath.has(imp.importPath)) {
        importsByPath.set(imp.importPath, { named: new Set(), defaults: new Set(), namespaces: new Set() });
      }
      const grp = importsByPath.get(imp.importPath);
      if (imp.kind === 'default') grp.defaults.add(imp.name);
      else if (imp.kind === 'namespace') grp.namespaces.add(imp.name);
      else grp.named.add(imp.name);
    }
  }

  const importLines = [];
  if (hasBridge) {
    importLines.push(
      esm
        ? `import { getFiodosBridge } from './${BRIDGE_BASENAME}';`
        : `const { getFiodosBridge } = require('./${BRIDGE_BASENAME}');`,
    );
  }
  for (const [p, grp] of importsByPath) {
    if (esm) {
      for (const local of grp.defaults) importLines.push(`import ${local} from '${p}';`);
      for (const local of grp.namespaces) importLines.push(`import * as ${local} from '${p}';`);
      if (grp.named.size) importLines.push(`import { ${[...grp.named].join(', ')} } from '${p}';`);
    } else {
      if (grp.named.size) importLines.push(`const { ${[...grp.named].join(', ')} } = require('${p}');`);
      for (const local of grp.defaults) importLines.push(`const ${local} = require('${p}');`);
      for (const local of grp.namespaces) importLines.push(`const ${local} = require('${p}');`);
    }
  }

  // Self-contained types (no @fyodos import) so the file typechecks even before
  // the SDK is installed; the shape MUST stay assignable to @fiodos/core's
  // ActionRegistries so `<FiodosAgent registries={...}/>` type-checks. In
  // particular idempotencyCheckers must match IdempotencyChecker —
  // `(context) => Promise<{ alreadyApplied; message? }>` — not a boolean.
  // Handlers accept the engine's optional (context, intent) trailing args so a
  // handler shared by several manifest actions can dispatch on the intent.
  const typeDefs = ts
    ? 'type FiodosActionResult = { success: boolean; data?: Record<string, unknown>; error?: string };\n' +
      'type FiodosRegistries = {\n' +
      '  handlers: Record<string, (params: Record<string, any>, context?: Record<string, any>, intent?: string) => Promise<FiodosActionResult>>;\n' +
      '  idempotencyCheckers: Record<string, (context: Record<string, any>) => Promise<{ alreadyApplied: boolean; message?: string }>>;\n' +
      '};\n'
    : '';
  const resultType = ts ? ': Promise<FiodosActionResult>' : '';
  const paramsType = ts ? ': Record<string, any>' : '';
  const intentType = ts ? ': string | undefined' : '';

  // Shared runner: one place normalizes any wired call into an action result,
  // so each handler below stays a one-liner. `unknown` keeps the truthiness
  // test legal even when the wired call returns void (e.g. db.delete(...)).
  // "is not a function" here means a BRIDGE method whose host screen is not
  // mounted yet — the SDK executor recognizes FYODOS_HANDLER_UNREADY, walks
  // the user to the screen that hosts the action and retries automatically.
  const runHelper = ts
    ? 'async function __fyodosRun(call: () => unknown): Promise<FiodosActionResult> {\n' +
      '  try {\n' +
      '    const result: unknown = await Promise.resolve(call());\n' +
      "    return { success: true, data: (result && typeof result === 'object') ? result as Record<string, unknown> : { result } };\n" +
      '  } catch (err) {\n' +
      '    const msg = err instanceof Error ? err.message : String(err);\n' +
      "    if (err instanceof TypeError && /is not a function/.test(msg)) {\n" +
      "      return { success: false, error: 'FYODOS_HANDLER_UNREADY: ' + msg };\n" +
      '    }\n' +
      '    return { success: false, error: msg };\n' +
      '  }\n' +
      '}\n'
    : 'async function __fyodosRun(call) {\n' +
      '  try {\n' +
      '    const result = await Promise.resolve(call());\n' +
      "    return { success: true, data: (result && typeof result === 'object') ? result : { result } };\n" +
      '  } catch (err) {\n' +
      '    const msg = err instanceof Error ? err.message : String(err);\n' +
      "    if (err instanceof TypeError && /is not a function/.test(msg)) {\n" +
      "      return { success: false, error: 'FYODOS_HANDLER_UNREADY: ' + msg };\n" +
      '    }\n' +
      '    return { success: false, error: msg };\n' +
      '  }\n' +
      '}\n';

  const entryTakesParams = (e) =>
    e.usesParams != null ? e.usesParams : /\bparams\b/.test(e.callExpr);

  // Group auto entries by handler name: several manifest actions may share one
  // handler (e.g. three section jumps calling scrollToSection with different
  // arguments). An object literal keeps only the LAST duplicate key, which
  // would silently break the others — so shared handlers dispatch on the
  // intent the engine passes as the third argument instead.
  const byHandler = new Map();
  for (const e of plan.auto) {
    if (!byHandler.has(e.handler)) byHandler.set(e.handler, []);
    byHandler.get(e.handler).push(e);
  }

  const handlerBlocks = [];
  for (const [handlerName, group] of byHandler) {
    const distinctCalls = new Set(group.map((e) => e.callExpr));
    if (group.length === 1 || distinctCalls.size === 1) {
      const e = group[0];
      const arg = entryTakesParams(e) ? `params${paramsType}` : `_params${paramsType}`;
      handlerBlocks.push(
        `    ${handlerName}: async (${arg})${resultType} => __fyodosRun(() => ${e.callExpr}),`,
      );
      continue;
    }
    const takesParams = group.some(entryTakesParams);
    const arg = takesParams ? `params${paramsType}` : `_params${paramsType}`;
    const cases = group
      .slice(1)
      .map((e) => `        case ${JSON.stringify(e.intent)}: return __fyodosRun(() => ${e.callExpr});`)
      .join('\n');
    handlerBlocks.push(
      `    ${handlerName}: async (${arg}, _context${ts ? ': Record<string, any> | undefined' : ''}, intent${intentType})${resultType} => {\n` +
      `      switch (intent) {\n` +
      `${cases}\n` +
      `        default: return __fyodosRun(() => ${group[0].callExpr});\n` +
      `      }\n` +
      `    },`,
    );
  }

  const handlerText = handlerBlocks.join('\n');

  // List each handler that needs manual wiring once. Skip any handler already
  // auto-wired above (the same handler name can back both an auto-wired and a
  // manual intent — listing it as "manual" would contradict the wired entry).
  const autoHandlers = new Set(plan.auto.map((e) => e.handler));
  const manualHandlers = [...new Set(plan.manual.map((e) => e.handler))].filter(
    (h) => !autoHandlers.has(h),
  );
  const manualNotes = manualHandlers.map(
    (h) => `    // ${h}: needs manual wiring — see ${DOC_BASENAME}`,
  );

  const header =
    `/** ${GENERATED_MARKER}. Do not edit — re-run the Fiodos installer to regenerate. */\n`;

  const decl = esm
    ? `export const ${REGISTRY_EXPORT}${ts ? ': FiodosRegistries' : ''} = {`
    : `const ${REGISTRY_EXPORT}${ts ? ': FiodosRegistries' : ''} = {`;

  const body =
    `${GENERATED_FILE_DIRECTIVES}` +
    `${header}\n` +
    `${importLines.join('\n')}\n\n` +
    (typeDefs ? `${typeDefs}\n` : '') +
    `${runHelper}\n` +
    `${decl}\n` +
    `  handlers: {\n` +
    `${handlerText}\n` +
    (manualNotes.length ? `${manualNotes.join('\n')}\n` : '') +
    `  },\n` +
    `  idempotencyCheckers: {},\n` +
    `};\n` +
    (esm ? '' : `\nmodule.exports = { ${REGISTRY_EXPORT} };\n`);

  return body;
}

/**
 * The bridge holder module: a tiny module-level registry the component writes
 * its LIVE in-scope functions into (registerFiodosBridge) and the generated
 * handlers read from (getFiodosBridge). This is what lets a standalone module
 * reach component-local state without ever creating a detached instance.
 */
function buildBridgeModule(opts = {}) {
  const ts = opts.ts !== false;
  const esm = opts.esm !== false;
  const header =
    `${GENERATED_FILE_DIRECTIVES}` +
    `/** ${GENERATED_MARKER} (bridge holder). Do not edit — re-run the Fiodos installer to regenerate. */\n`;
  if (ts) {
    return (
      `${header}\n` +
      `type FiodosBridge = Record<string, (args: any) => any>;\n\n` +
      `let __fyodosBridge: FiodosBridge = {};\n\n` +
      `export function registerFiodosBridge(fns: FiodosBridge): void {\n` +
      `  __fyodosBridge = { ...__fyodosBridge, ...fns };\n` +
      `}\n\n` +
      `export function getFiodosBridge(): FiodosBridge {\n` +
      `  return __fyodosBridge;\n` +
      `}\n`
    );
  }
  if (esm) {
    return (
      `${header}\n` +
      `let __fyodosBridge = {};\n\n` +
      `export function registerFiodosBridge(fns) {\n` +
      `  __fyodosBridge = { ...__fyodosBridge, ...fns };\n` +
      `}\n\n` +
      `export function getFiodosBridge() {\n` +
      `  return __fyodosBridge;\n` +
      `}\n`
    );
  }
  return (
    `${header}\n` +
    `let __fyodosBridge = {};\n\n` +
    `function registerFiodosBridge(fns) {\n` +
    `  __fyodosBridge = { ...__fyodosBridge, ...fns };\n` +
    `}\n\n` +
    `function getFiodosBridge() {\n` +
    `  return __fyodosBridge;\n` +
    `}\n\n` +
    `module.exports = { registerFiodosBridge, getFiodosBridge };\n`
  );
}

/**
 * Plan the edits to the user's own component files for all BRIDGE entries.
 * Groups bridge entries by component file and produces, per file:
 *   · the import line for registerFiodosBridge (+ any extra imports invoke needs),
 *   · a single registerFiodosBridge({...}) block,
 *   · the anchor after which the block is inserted (the one occurring LAST in
 *     the file among the group, so every referenced symbol is already defined).
 * The actual mutation/idempotence/backup happens in applyComponentEdits.
 */
function planComponentEdits(appRoot, plan, opts = {}) {
  const ts = opts.ts !== false;
  const byFile = new Map();
  for (const e of plan.auto) {
    if (e.kind !== 'bridge') continue;
    if (!byFile.has(e.bridge.file)) byFile.set(e.bridge.file, []);
    byFile.get(e.bridge.file).push(e);
  }

  const edits = [];
  for (const [file, entries] of byFile) {
    const content = readFileSafe(appRoot, file) || '';
    // Pick the anchor that appears LAST in the file (all symbols defined by then).
    let anchor = entries[0].bridge.anchor;
    let bestIdx = content.indexOf(anchor);
    for (const e of entries) {
      const idx = content.indexOf(e.bridge.anchor);
      if (idx > bestIdx) {
        bestIdx = idx;
        anchor = e.bridge.anchor;
      }
    }

    const classField = entries.some((e) => e.bridge.scope === 'class-field');
    const methods = entries.map((e) => {
      const inv = e.bridge.invoke;
      // This code lands in the USER's file, so it cannot carry `@ts-nocheck`; it
      // must be lint- and type-clean by construction:
      //  · NO explicit `any` annotation — the param type comes contextually from
      //    registerFiodosBridge's signature, so there is no `no-explicit-any` and
      //    no implicit-any either.
      //  · OMIT the param entirely when the invocation never reads it, so strict
      //    `no-unused-vars` cannot fire (TS allows callbacks with fewer params).
      const usesArgs = /\bargs\b/.test(inv);
      const param = usesArgs ? 'args' : '';
      return `  ${JSON.stringify(e.bridge.method)}: (${param}) => (${inv}),`;
    });

    // Imports: registerFiodosBridge + any extra the invokes need (deduped).
    const importPathToBridge = entries[0].bridge.importPathToBridge;
    const importLines = [`import { registerFiodosBridge } from '${importPathToBridge}';`];
    const seen = new Set();
    for (const e of entries) {
      for (const imp of e.bridge.imports || []) {
        const key = `${imp.kind}:${imp.name}:${imp.importPath}`;
        if (seen.has(key)) continue;
        seen.add(key);
        if (imp.kind === 'default') importLines.push(`import ${imp.name} from '${imp.importPath}';`);
        else if (imp.kind === 'namespace') importLines.push(`import * as ${imp.name} from '${imp.importPath}';`);
        else importLines.push(`import { ${imp.name} } from '${imp.importPath}';`);
      }
    }

    // In a class body a bare call is a syntax error; bind it to a field so the
    // arrow functions capture the live `this` (the real injected instance).
    const registerCall = classField
      ? `private __fyodosBridge = registerFiodosBridge({\n${methods.join('\n')}\n});`
      : `registerFiodosBridge({\n${methods.join('\n')}\n});`;
    // Fence our insertion from the project's ESLint config (style rules only — the
    // code itself is clean and type-checked). `@ts-nocheck` can't be scoped to a
    // block inside the user's file, so type-correctness is guaranteed by codegen.
    const registerBlock = `${EDIT_START}\n${INJECT_ESLINT_DISABLE}\n${registerCall}\n${INJECT_ESLINT_ENABLE}\n${EDIT_END}`;

    // Match the anchor's leading indentation so the inserted block stays tidy.
    const lineStart = content.lastIndexOf('\n', bestIdx) + 1;
    const indent = (content.slice(lineStart, bestIdx).match(/^\s*/) || [''])[0];

    edits.push({
      file,
      anchor,
      scope: classField ? 'class-field' : 'statement',
      importBlock: `${EDIT_START}\n${INJECT_ESLINT_DISABLE}\n${importLines.join('\n')}\n${INJECT_ESLINT_ENABLE}\n${EDIT_END}`,
      registerBlock: registerBlock.split('\n').map((l) => (l ? indent + l : l)).join('\n'),
      intents: entries.map((e) => e.intent),
    });
  }
  return edits;
}

