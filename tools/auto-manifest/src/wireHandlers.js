// ── Editing the user's own files (idempotent + reversible) ─────────────────────

/**
 * Header phrasings the CLI itself has ever written (current English + the
 * localized parenthetical of older versions). Only blocks carrying one of
 * these are OURS to strip.
 */
const GENERATED_HEADER_RE = /(generated by|auto-generado por|generado por)\s+Fiodos/i;

/**
 * Remove previously-inserted Fiodos blocks (idempotence across re-runs) —
 * but ONLY the blocks this CLI generated. A developer can hand-write their
 * own `FYODOS:BRIDGE` block (e.g. "manual wiring — logout") following our
 * docs; that block is THEIR code and often the only user of an import
 * (`useEffect`, a hook…). Stripping it orphans the import, the strict
 * TypeScript check (noUnusedLocals) fails the candidate, and the whole
 * wiring reverts — the exact failure that left navigate_section/logout
 * unwired in production. Developer blocks are preserved verbatim.
 */
function stripFiodosBlocks(content) {
  const re = new RegExp(
    `\\n?(${esc(EDIT_START_PREFIX)}[^\\n]*)[\\s\\S]*?${esc(EDIT_END)}\\n?`,
    'g',
  );
  return content.replace(re, (block, headerLine) =>
    GENERATED_HEADER_RE.test(headerLine) ? '\n' : block,
  );
}

/** Insert an import block right after the file's last top-level import statement.
 *  Matches the WHOLE statement through its module string — a per-line regex put
 *  the block INSIDE multi-line imports (`import {\n  a,\n} from 'x';`), corrupting
 *  the file (TS1003 "Identifier expected") and failing the wiring of every action
 *  in that file. `[^'"]*` cannot skip a quote, so the match always stops at the
 *  first quoted module specifier, then runs to that line's end. */
function insertImportBlock(content, importBlock) {
  const importLineRe = /^[ \t]*import\b[^'"]*['"][^'"]+['"][^\n]*\n/gm;
  let lastEnd = -1;
  let m;
  while ((m = importLineRe.exec(content))) lastEnd = m.index + m[0].length;
  if (lastEnd === -1) {
    // No imports (rare). Put it after a leading <script ...> tag if present.
    const scriptM = content.match(/<script\b[^>]*>\s*\n/);
    if (scriptM) {
      const at = scriptM.index + scriptM[0].length;
      return content.slice(0, at) + importBlock + '\n' + content.slice(at);
    }
    return importBlock + '\n' + content;
  }
  return content.slice(0, lastEnd) + importBlock + '\n' + content.slice(lastEnd);
}

/** Index of the JSX/paren `return (` or `return <` line nearest to `anchorIdx`. */
function nearestJsxReturn(content, anchorIdx) {
  const re = /^[ \t]*return\s*[(<]/gm;
  let best = -1;
  let bestDist = Infinity;
  let m;
  while ((m = re.exec(content))) {
    const dist = Math.abs(m.index - anchorIdx);
    if (dist < bestDist) { bestDist = dist; best = m.index; }
  }
  return best;
}

/**
 * Insert the registration block at a SYNTACTICALLY VALID spot:
 *   · .vue files → just before the last </script>,
 *   · class-field scope (Angular @Component) → right AFTER the anchor line, inside
 *     the class body (the anchor is a sibling class field),
 *   · statement scope (React/JS function component) → just BEFORE the JSX `return`
 *     nearest the anchor, so the call is always a statement and NEVER lands inside
 *     JSX (which produced `Expected "}" but found ":"`). The AI's anchor only needs
 *     to locate the right component, not the exact insertion line.
 *   · fallback (no JSX return: object-returning factories, etc.) → before a
 *     `return` anchor, else after the anchor line.
 */
function insertRegisterBlock(content, file, anchor, block, scope) {
  if (file.endsWith('.vue')) {
    const close = content.lastIndexOf('</script>');
    if (close !== -1) {
      const lineStart = content.lastIndexOf('\n', close) + 1;
      return content.slice(0, lineStart) + block + '\n' + content.slice(lineStart);
    }
  }
  const at = content.indexOf(anchor);
  if (at === -1) return content; // verified earlier; defensive

  if (scope === 'class-field') {
    const lineEnd = content.indexOf('\n', at);
    const endIdx = lineEnd === -1 ? content.length : lineEnd;
    return content.slice(0, endIdx) + '\n' + block + content.slice(endIdx);
  }

  // When the anchor's own line is unmistakably a body STATEMENT (a declaration
  // or a bare call ending in `;`), insert right AFTER it. Snapping to the
  // nearest `return` instead can land the registration inside a conditional
  // early-return branch (`if (authLoading) { … return <Spinner/> }`): it
  // compiles, but in normal use that branch never runs and the bridge is never
  // registered — the action silently dies at runtime.
  const anchorLineStart = content.lastIndexOf('\n', at) + 1;
  const anchorLineEnd = content.indexOf('\n', at);
  const anchorLine = content.slice(anchorLineStart, anchorLineEnd === -1 ? content.length : anchorLineEnd).trim();
  const isStatementLine =
    /^(const|let|var)\b.*;\s*$/.test(anchorLine) || /^[\w$][\w$.]*\((?:[^()]|\([^()]*\))*\);\s*$/.test(anchorLine);
  if (isStatementLine) {
    // A multi-line declaration (`const { a, b } =\n  useApp();`) ends at the
    // first `;` at/after the anchor, not at the anchor's own line end.
    const semi = content.indexOf(';', at);
    const stmtEnd = semi === -1 ? (anchorLineEnd === -1 ? content.length : anchorLineEnd) : content.indexOf('\n', semi);
    const endIdx = stmtEnd === -1 ? content.length : stmtEnd;
    return content.slice(0, endIdx) + '\n' + block + content.slice(endIdx);
  }

  const ret = nearestJsxReturn(content, at);
  if (ret !== -1) {
    const lineStart = content.lastIndexOf('\n', ret) + 1;
    return content.slice(0, lineStart) + block + '\n' + content.slice(lineStart);
  }

  const lineStart = content.lastIndexOf('\n', at) + 1;
  if (anchor.trim().startsWith('return')) {
    return content.slice(0, lineStart) + block + '\n' + content.slice(lineStart);
  }
  const lineEnd = content.indexOf('\n', at);
  const endIdx = lineEnd === -1 ? content.length : lineEnd;
  return content.slice(0, endIdx) + '\n' + block + content.slice(endIdx);
}

/**
 * Apply all planned component edits. Snapshots each file's original content
 * first (for clean revert) and is idempotent (strips prior Fiodos blocks before
 * re-inserting). Returns { backups: [{file, original}], edited: [file...] }.
 */
function applyComponentEdits(appRoot, edits) {
  const backups = [];
  const edited = [];
  for (const edit of edits) {
    const abs = path.join(appRoot, normRel(edit.file));
    const original = fs.readFileSync(abs, 'utf8');
    backups.push({ file: edit.file, abs, original });

    let next = stripFiodosBlocks(original);
    next = insertImportBlock(next, edit.importBlock);
    next = insertRegisterBlock(next, edit.file, edit.anchor, edit.registerBlock, edit.scope);
    fs.writeFileSync(abs, next);
    edited.push(edit.file);
  }
  return { backups, edited };
}

/**
 * Map regression error lines back to the specific entries that caused them, so
 * we can revert ONLY the offending actions instead of the whole batch:
 *   · BRIDGE entries → the error references the user file we edited (by basename).
 *   · MODULE entries → the error sits in handlers.generated and mentions the
 *     intent / handler / call expression of that entry.
 * Returns a Set of culprit intents. Empty means "could not isolate" (the caller
 * then falls back to a full revert rather than guessing).
 */
function attributeCulprits(entries, errorLines) {
  const culprits = new Set();
  const lines = (errorLines || []).map(String);
  if (!lines.length) return culprits;
  for (const e of entries || []) {
    const intent = e.intent;
    if (e.kind === 'bridge') {
      const base = path.basename(normRel(e.bridge && e.bridge.file));
      if (base && lines.some((l) => l.includes(base))) culprits.add(intent);
    } else {
      const tokens = [intent, e.handler, e.callExpr].filter(Boolean).map(String);
      const inRegistry = lines.some(
        (l) => /handlers\.generated/i.test(l) && tokens.some((t) => t && l.includes(t)),
      );
      if (inRegistry) culprits.add(intent);
    }
  }
  return culprits;
}

/** Restore files to their pre-edit content and delete generated files. */
function revertAll(backups, generatedFiles) {
  for (const b of backups || []) {
    try {
      fs.writeFileSync(b.abs, b.original);
    } catch {
      /* best effort */
    }
  }
  for (const f of generatedFiles || []) {
    try {
      if (fs.existsSync(f)) fs.rmSync(f);
    } catch {
      /* best effort */
    }
  }
}

