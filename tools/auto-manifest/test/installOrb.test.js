/**
 * `fiodos install` — the command that exists so nobody pastes JavaScript.
 *
 * What these tests defend is not the text it writes but the promises around it:
 * running it twice leaves one orb, a failure leaves the app untouched, and the
 * shape it picks is the one that will actually RUN in that app — a distinction
 * with no visible symptom until the orb silently never appears.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const {
  addModuleImport,
  applyInstall,
  deployNotice,
  injectIntoHtml,
  isAlreadyInstalled,
  planInstall,
} = require('../src/installOrb');

const PAYLOAD = {
  snippet: [
    '<!-- FYODOS:ORB:START (generated by Fiodos — safe to remove) -->',
    '<script src="https://unpkg.com/@fiodos/web-core@latest/dist/embed/fiodos-embed.js" defer></script>',
    '<script>window.__mounted = true;</script>',
    '<!-- FYODOS:ORB:END -->',
  ].join('\n'),
  module: "(function () { /* orb */ })();\n",
  moduleBasename: 'fyodos-orb',
};

function scratch(name) {
  return fs.mkdtempSync(path.join(os.tmpdir(), `fyodos-install-${name}-`));
}

function writeApp(root, files) {
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
  return root;
}

const HTML = ['<html>', '  <body>', '    <div id="root"></div>', '  </body>', '</html>', ''].join(
  '\n',
);

// ── The block lands where the browser will read it ──────────────────────────

test('the block goes in just before </body>, indented like its neighbours', () => {
  const out = injectIntoHtml(HTML, PAYLOAD.snippet);

  const lines = out.split('\n');
  const closing = lines.findIndex((l) => l.includes('</body>'));
  assert.ok(lines[closing - 1].includes('FYODOS:ORB:END'));
  assert.ok(lines.some((l) => l.startsWith('    <!-- FYODOS:ORB:START')));
});

test('an HTML file with no </body> is refused rather than guessed at', () => {
  assert.strictEqual(injectIntoHtml('<div>fragment</div>', PAYLOAD.snippet), null);
});

test('installing twice leaves exactly one orb', () => {
  const once = injectIntoHtml(HTML, PAYLOAD.snippet);
  const twice = injectIntoHtml(once, PAYLOAD.snippet);

  assert.strictEqual(twice.match(/FYODOS:ORB:START/g).length, 1);
  assert.strictEqual(twice, once);
});

test('the import into an entry file also replaces instead of stacking', () => {
  const entry = "import App from './App';\ncreateRoot(el).render(<App />);\n";

  const once = addModuleImport(entry, './fyodos-orb');
  const twice = addModuleImport(once, './fyodos-orb');

  assert.strictEqual(twice.match(/fyodos-orb/g).length, 1);
  assert.ok(twice.includes("import App from './App';"));
});

// ── The shape has to be one that runs in THAT app ───────────────────────────

test('an app with an HTML shell takes the block', () => {
  const root = writeApp(scratch('vite'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
    'src/main.tsx': 'createRoot(el).render(<App />);\n',
  });

  const plan = planInstall(root);

  assert.strictEqual(plan.strategy, 'html-shell');
  assert.strictEqual(plan.rel, 'index.html');
});

test('a Next app is never given a stray public/index.html', () => {
  // Next serves no static shell. Writing there produces an install that looks
  // successful in the terminal and never runs in the browser — the worst
  // possible outcome, because nothing reports it.
  const root = writeApp(scratch('next'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    'public/index.html': HTML,
    'app/layout.tsx': 'export default function L({children}){return (<html><body>{children}</body></html>);}\n',
  });

  const plan = planInstall(root);

  assert.strictEqual(plan.strategy, 'next-app');
  assert.ok(plan.rel.includes('layout'));
});

test('an app whose shell is JSX takes the module and an import', () => {
  const root = writeApp(scratch('entry'), {
    'package.json': JSON.stringify({ dependencies: { vue: '^3' } }),
    'src/main.ts': "import { createApp } from 'vue';\ncreateApp().mount('#app');\n",
  });

  const plan = planInstall(root);

  assert.strictEqual(plan.strategy, 'entry-import');
});

test('an app we cannot recognise says so instead of writing somewhere random', () => {
  const root = writeApp(scratch('empty'), { 'README.md': '# hello\n' });

  const plan = planInstall(root);

  assert.strictEqual(plan.ok, false);
  assert.match(plan.reason, /index\.html/);
});

// ── Writing, and undoing it ─────────────────────────────────────────────────

test('a Next install reaches the browser through a client component', () => {
  // app/layout.tsx is a server component: whatever IT imports is bundled for
  // the server and never shipped, so the orb would never load.
  const root = writeApp(scratch('next-apply'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    'app/layout.tsx': 'export default function L({children}){return (<html><body>{children}</body></html>);}\n',
  });

  const touched = applyInstall(root, planInstall(root), PAYLOAD);

  const layout = fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8');
  assert.ok(layout.includes('<FyodosOrb />'));
  const client = fs.readFileSync(path.join(root, 'app/fyodos-orb-client.tsx'), 'utf8');
  assert.ok(client.startsWith("'use client';"));
  assert.ok(client.includes('useEffect'));
  assert.ok(fs.existsSync(path.join(root, 'app/fyodos-orb.js')));
  assert.deepStrictEqual(touched, [
    'app/fyodos-orb.js',
    'app/fyodos-orb-client.tsx',
    'app/layout.tsx',
    'FYODOS_ORB_INSTALL.md',
  ]);
});

// ── What it leaves behind for whoever reviews it ────────────────────────────

test('it writes down what it changed, for the person who did not run it', () => {
  // The terminal that printed "done" will be closed in a minute, and whoever
  // opens the pull request tomorrow was not there. Without this, a reviewer
  // finds unexplained edits from a tool they did not run.
  const root = writeApp(scratch('report'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });

  applyInstall(root, planInstall(root), PAYLOAD);

  const report = fs.readFileSync(path.join(root, 'FYODOS_ORB_INSTALL.md'), 'utf8');
  assert.match(report, /index\.html/);
  assert.match(report, /FYODOS:ORB/);
  // The two questions a reviewer actually has.
  assert.match(report, /## To remove it/);
  assert.match(report, /## To make it appear in production/);
});

test('a failed install leaves no report of an install that did not happen', () => {
  const root = writeApp(scratch('report-revert'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    'app/layout.tsx': 'export default function L({children}){return children;}\n',
  });

  assert.throws(() => applyInstall(root, planInstall(root), PAYLOAD));

  assert.strictEqual(fs.existsSync(path.join(root, 'FYODOS_ORB_INSTALL.md')), false);
});

const noticeText = () => deployNotice().join('\n');

test('the notice is one reminder, not a tutorial', () => {
  // The old CLI printed three numbered steps here because the key it wrote
  // came from a build-time variable that never reached the host. The block we
  // write carries the key, so there is nothing to configure — and a step that
  // does nothing would send people looking in the wrong place.
  assert.strictEqual(deployNotice().length, 1);
  assert.doesNotMatch(noticeText(), /Step \d|Environment Variables|FYODOS_API_KEY/);
});

test('the notice names no host and no command', () => {
  // We do not know their pipeline. Naming a service or a command we merely
  // guessed at sends anybody whose workflow differs looking for a button that
  // is not there. "Publish" is true for a push, a build or an upload alike.
  const notice = noticeText();

  assert.doesNotMatch(notice, /Vercel|Netlify|Cloudflare|GitHub/i);
  assert.doesNotMatch(notice, /\bgit\b|npm run/);
  assert.match(notice, /Publish these changes/);
});

test('the report keeps the cache tip the terminal no longer prints', () => {
  // Not showing up after a deploy is nearly always a cached page. It does not
  // belong in a one-line reminder, but it does belong somewhere.
  const root = writeApp(scratch('cache'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });

  applyInstall(root, planInstall(root), PAYLOAD);

  const report = fs.readFileSync(path.join(root, 'FYODOS_ORB_INSTALL.md'), 'utf8');
  assert.match(report, /Shift \+ R/);
});

test('a failed install leaves the app exactly as it was', () => {
  const root = writeApp(scratch('revert'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    // A layout with no </body>: the mount cannot be placed, so nothing may be
    // left behind — not the module, not the client component, nothing.
    'app/layout.tsx': 'export default function L({children}){return children;}\n',
  });
  const before = fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8');

  assert.throws(() => applyInstall(root, planInstall(root), PAYLOAD));

  assert.strictEqual(fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8'), before);
  assert.strictEqual(fs.existsSync(path.join(root, 'app/fyodos-orb.js')), false);
  assert.strictEqual(fs.existsSync(path.join(root, 'app/fyodos-orb-client.tsx')), false);
});

test('an app that already carries an orb is recognised as such', () => {
  const root = writeApp(scratch('already'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });
  const plan = planInstall(root);
  assert.strictEqual(isAlreadyInstalled(root, plan), false);

  applyInstall(root, plan, PAYLOAD);

  assert.strictEqual(isAlreadyInstalled(root, plan), true);
});
