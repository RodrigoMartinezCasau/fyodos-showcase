/**
 * `fiodos install` — the command that exists so nobody pastes JavaScript.
 *
 * What these tests defend is not the text it writes but the promises around it:
 * running it twice leaves one orb, a failure leaves the app untouched, and the
 * shape it picks is the one that will actually RUN in that app — a distinction
 * with no visible symptom until the orb silently never appears.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const {
  addModuleImport,
  applyInstall,
  deployNotice,
  injectIntoHtml,
  isAlreadyInstalled,
  planInstall,
  summarizeManifest,
} = require('../src/installOrb');

const PAYLOAD = {
  snippet: [
    '<!-- FYODOS:ORB:START (generated by Fiodos — safe to remove) -->',
    '<script src="https://unpkg.com/@fiodos/web-core@latest/dist/embed/fiodos-embed.js" defer></script>',
    '<script>window.__mounted = true;</script>',
    '<!-- FYODOS:ORB:END -->',
  ].join('\n'),
  module: "(function () { /* orb */ })();\n",
  moduleBasename: 'fyodos-orb',
};

function scratch(name) {
  return fs.mkdtempSync(path.join(os.tmpdir(), `fyodos-install-${name}-`));
}

function writeApp(root, files) {
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
  return root;
}

const HTML = ['<html>', '  <body>', '    <div id="root"></div>', '  </body>', '</html>', ''].join(
  '\n',
);

// ── The block lands where the browser will read it ──────────────────────────

test('the block goes in just before </body>, indented like its neighbours', () => {
  const out = injectIntoHtml(HTML, PAYLOAD.snippet);

  const lines = out.split('\n');
  const closing = lines.findIndex((l) => l.includes('</body>'));
  assert.ok(lines[closing - 1].includes('FYODOS:ORB:END'));
  assert.ok(lines.some((l) => l.startsWith('    <!-- FYODOS:ORB:START')));
});

test('an HTML file with no </body> is refused rather than guessed at', () => {
  assert.strictEqual(injectIntoHtml('<div>fragment</div>', PAYLOAD.snippet), null);
});

test('installing twice leaves exactly one orb', () => {
  const once = injectIntoHtml(HTML, PAYLOAD.snippet);
  const twice = injectIntoHtml(once, PAYLOAD.snippet);

  assert.strictEqual(twice.match(/FYODOS:ORB:START/g).length, 1);
  assert.strictEqual(twice, once);
});

test('the import into an entry file also replaces instead of stacking', () => {
  const entry = "import App from './App';\ncreateRoot(el).render(<App />);\n";

  const once = addModuleImport(entry, './fyodos-orb');
  const twice = addModuleImport(once, './fyodos-orb');

  assert.strictEqual(twice.match(/fyodos-orb/g).length, 1);
  assert.ok(twice.includes("import App from './App';"));
});

// ── The shape has to be one that runs in THAT app ───────────────────────────

test('an app with an HTML shell takes the block', () => {
  const root = writeApp(scratch('vite'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
    'src/main.tsx': 'createRoot(el).render(<App />);\n',
  });

  const plan = planInstall(root);

  assert.strictEqual(plan.strategy, 'html-shell');
  assert.strictEqual(plan.rel, 'index.html');
});

test('a Next app is never given a stray public/index.html', () => {
  // Next serves no static shell. Writing there produces an install that looks
  // successful in the terminal and never runs in the browser — the worst
  // possible outcome, because nothing reports it.
  const root = writeApp(scratch('next'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    'public/index.html': HTML,
    'app/layout.tsx': 'export default function L({children}){return (<html><body>{children}</body></html>);}\n',
  });

  const plan = planInstall(root);

  assert.strictEqual(plan.strategy, 'next-app');
  assert.ok(plan.rel.includes('layout'));
});

test('an app whose shell is JSX takes the module and an import', () => {
  const root = writeApp(scratch('entry'), {
    'package.json': JSON.stringify({ dependencies: { vue: '^3' } }),
    'src/main.ts': "import { createApp } from 'vue';\ncreateApp().mount('#app');\n",
  });

  const plan = planInstall(root);

  assert.strictEqual(plan.strategy, 'entry-import');
});

test('an app we cannot recognise says so instead of writing somewhere random', () => {
  const root = writeApp(scratch('empty'), { 'README.md': '# hello\n' });

  const plan = planInstall(root);

  assert.strictEqual(plan.ok, false);
  assert.match(plan.reason, /index\.html/);
});

// ── Writing, and undoing it ─────────────────────────────────────────────────

test('a Next install reaches the browser through a client component', () => {
  // app/layout.tsx is a server component: whatever IT imports is bundled for
  // the server and never shipped, so the orb would never load.
  const root = writeApp(scratch('next-apply'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    'app/layout.tsx': 'export default function L({children}){return (<html><body>{children}</body></html>);}\n',
  });

  const touched = applyInstall(root, planInstall(root), PAYLOAD);

  const layout = fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8');
  assert.ok(layout.includes('<FyodosOrb />'));
  const client = fs.readFileSync(path.join(root, 'app/fyodos-orb-client.tsx'), 'utf8');
  assert.ok(client.startsWith("'use client';"));
  assert.ok(client.includes('useEffect'));
  assert.ok(fs.existsSync(path.join(root, 'app/fyodos-orb.js')));
  assert.deepStrictEqual(touched, [
    'app/fyodos-orb.js',
    'app/fyodos-orb-client.tsx',
    'app/layout.tsx',
    'FYODOS_ORB_INSTALL.md',
  ]);
});

// ── What it leaves behind for whoever reviews it ────────────────────────────

test('it writes down what it changed, for the person who did not run it', () => {
  // The terminal that printed "done" will be closed in a minute, and whoever
  // opens the pull request tomorrow was not there. Without this, a reviewer
  // finds unexplained edits from a tool they did not run.
  const root = writeApp(scratch('report'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });

  applyInstall(root, planInstall(root), PAYLOAD);

  const report = fs.readFileSync(path.join(root, 'FYODOS_ORB_INSTALL.md'), 'utf8');
  assert.match(report, /index\.html/);
  assert.match(report, /FYODOS:ORB/);
  // The two questions a reviewer actually has.
  assert.match(report, /## To remove it/);
  assert.match(report, /## To make it appear in production/);
});

test('a failed install leaves no report of an install that did not happen', () => {
  const root = writeApp(scratch('report-revert'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    'app/layout.tsx': 'export default function L({children}){return children;}\n',
  });

  assert.throws(() => applyInstall(root, planInstall(root), PAYLOAD));

  assert.strictEqual(fs.existsSync(path.join(root, 'FYODOS_ORB_INSTALL.md')), false);
});

const noticeText = () => deployNotice().join('\n');

test('the notice is one reminder, not a tutorial', () => {
  // The old CLI printed three numbered steps here because the key it wrote
  // came from a build-time variable that never reached the host. The block we
  // write carries the key, so there is nothing to configure — and a step that
  // does nothing would send people looking in the wrong place.
  assert.strictEqual(deployNotice().length, 1);
  assert.doesNotMatch(noticeText(), /Step \d|Environment Variables|FYODOS_API_KEY/);
});

test('the notice names no host and no command', () => {
  // We do not know their pipeline. Naming a service or a command we merely
  // guessed at sends anybody whose workflow differs looking for a button that
  // is not there. "Publish" is true for a push, a build or an upload alike.
  const notice = noticeText();

  assert.doesNotMatch(notice, /Vercel|Netlify|Cloudflare|GitHub/i);
  assert.doesNotMatch(notice, /\bgit\b|npm run/);
  assert.match(notice, /Publish these changes/);
});

test('the report keeps the cache tip the terminal no longer prints', () => {
  // Not showing up after a deploy is nearly always a cached page. It does not
  // belong in a one-line reminder, but it does belong somewhere.
  const root = writeApp(scratch('cache'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });

  applyInstall(root, planInstall(root), PAYLOAD);

  const report = fs.readFileSync(path.join(root, 'FYODOS_ORB_INSTALL.md'), 'utf8');
  assert.match(report, /Shift \+ R/);
});

test('a failed install leaves the app exactly as it was', () => {
  const root = writeApp(scratch('revert'), {
    'package.json': JSON.stringify({ dependencies: { next: '^14' } }),
    // A layout with no </body>: the mount cannot be placed, so nothing may be
    // left behind — not the module, not the client component, nothing.
    'app/layout.tsx': 'export default function L({children}){return children;}\n',
  });
  const before = fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8');

  assert.throws(() => applyInstall(root, planInstall(root), PAYLOAD));

  assert.strictEqual(fs.readFileSync(path.join(root, 'app/layout.tsx'), 'utf8'), before);
  assert.strictEqual(fs.existsSync(path.join(root, 'app/fyodos-orb.js')), false);
  assert.strictEqual(fs.existsSync(path.join(root, 'app/fyodos-orb-client.tsx')), false);
});

// ── The report says what the orb can DO here, not what installers do ────────

const MANIFEST = {
  appName: 'Test app',
  routes: [
    { intent: 'go_home', label: 'Home', route: '/' },
    { intent: 'go_account', label: 'Your account', route: '/account' },
  ],
  actions: [
    { intent: 'search_items', label: 'Search items', category: 'items', requireConfirmation: false },
    { intent: 'delete_item', label: 'Delete an item', category: 'items', requireConfirmation: true },
    {
      intent: 'change_email',
      label: 'Change your email',
      category: 'account',
      requireConfirmation: true,
      contextRequirements: { requiresAuth: true },
    },
    { intent: 'open_docs', label: 'Open the documentation', kind: 'link' },
  ],
};

/** The lines under one heading, so a name can be checked where it BELONGS. */
function section(report, heading) {
  const lines = report.split('\n');
  const from = lines.findIndex((l) => l.trim() === heading);
  if (from === -1) return '';
  const rest = lines.slice(from + 1);
  const to = rest.findIndex((l) => /^#{2,3} /.test(l));
  return (to === -1 ? rest : rest.slice(0, to)).join('\n');
}

function installWith(name, capability) {
  const root = writeApp(scratch(name), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });
  const touched = applyInstall(root, planInstall(root), PAYLOAD, { capability });
  return { root, touched, report: fs.readFileSync(path.join(root, 'FYODOS_ORB_INSTALL.md'), 'utf8') };
}

test('the report names the screens the orb can open, with their addresses', () => {
  const { report } = installWith('report-screens', { summary: summarizeManifest(MANIFEST) });

  const screens = section(report, '### Screens it can take a visitor to');
  assert.match(screens, /\*\*Your account\*\* — `\/account`/);
  assert.match(screens, /\*\*Home\*\* — `\/`/);
});

test('the report groups the actions so a human can read them', () => {
  const { report } = installWith('report-actions', { summary: summarizeManifest(MANIFEST) });

  const actions = section(report, '### Actions it can run');
  assert.match(actions, /\*\*items\*\* \(2\)/);
  assert.match(actions, /\*\*account\*\* \(1\)/);
  // An action the app performs without app code is grouped by THAT, which is
  // the useful fact about it, rather than by a family it never declared.
  assert.match(actions, /\*\*links\*\* \(1\)/);
  assert.match(actions, /\*\*Search items\*\*/);
  assert.match(actions, /\*\*Open the documentation\*\*/);
});

test('the report says which actions ask first and which need a signed-in visitor', () => {
  const { report } = installWith('report-gates', { summary: summarizeManifest(MANIFEST) });

  // Marked ON the action, not repeated in lists of the same names underneath:
  // on an API built for the person signed in that second list is nearly every
  // action, and printing all of them twice more is how a report stops being
  // read to the end.
  const actions = section(report, '### Actions it can run');
  assert.match(actions, /\*\*Delete an item\*\* — asks first/);
  assert.match(actions, /\*\*Change your email\*\* — asks first, signed-in visitors only/);
  assert.doesNotMatch(actions, /\*\*Search items\*\* — asks first/);
  assert.doesNotMatch(actions, /\*\*Delete an item\*\*[^\n]*signed-in/);

  const counts = section(report, '### Which of them stop, and which need somebody signed in');
  assert.match(counts, /2 of 4 ask before they run/);
  assert.match(counts, /1 need a signed-in visitor/);
});

test('both spellings of the same field are read, because both are served', () => {
  // The client endpoint serves the manifest as the CLI published it; the prompt
  // serializer renames the same fields on the way to the agent. A report that
  // knew only one spelling would call a guarded action unguarded.
  const summary = summarizeManifest({
    routes: [],
    actions: [
      { intent: 'pay', label: 'Pay', requires_confirmation: true, requires_auth: true },
    ],
  });

  assert.deepStrictEqual(summary.confirming, ['Pay']);
  assert.deepStrictEqual(summary.signedIn, ['Pay']);
});

test('a project with nothing published is told so, not given an empty list', () => {
  const { report } = installWith('report-empty', { summary: null });

  const what = section(report, '## What your orb can do on this site');
  assert.match(what, /no published manifest/);
  assert.match(what, /dashboard/);
  // Never a count of zero dressed up as a report of the orb's abilities.
  assert.doesNotMatch(what, /0 screen/);
});

test('a backend that did not answer costs a paragraph, never the install', () => {
  // The block is what makes the orb work, and it is already in the file. Losing
  // the install over the REPORT would trade the working thing for the account
  // of it.
  const { root, report, touched } = installWith('report-unreachable', {
    unavailable: 'we could not reach https://api.example.test',
  });

  assert.match(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), /FYODOS:ORB:START/);
  assert.deepStrictEqual(touched, ['index.html', 'FYODOS_ORB_INSTALL.md']);

  const what = section(report, '## What your orb can do on this site');
  assert.match(what, /Could not be read/);
  assert.match(what, /we could not reach https:\/\/api\.example\.test/);
  assert.match(what, /install itself is complete/);
  assert.match(what, /dashboard/);
});

test('an empty manifest reports the gap in the words that close it', () => {
  const { report } = installWith('report-gaps', {
    summary: summarizeManifest({ appName: 'Test app', routes: [], actions: [] }),
  });

  const gaps = section(report, '### Not there yet');
  assert.match(gaps, /No screens were published/);
  assert.match(gaps, /No actions were published/);
  assert.match(gaps, /analysis/);
});

test('the install describes no mount it did not create', () => {
  // The old drop-in generated a React mount and a document about it. This
  // command writes a script block; a file describing the other thing would send
  // whoever reads it looking for code that is not there.
  const { root, touched, report } = installWith('no-mount-doc', {
    summary: summarizeManifest(MANIFEST),
  });

  assert.deepStrictEqual(touched, ['index.html', 'FYODOS_ORB_INSTALL.md']);
  assert.strictEqual(fs.existsSync(path.join(root, 'src/fyodos')), false);
  assert.doesNotMatch(report, /FYODOS_ORB_MOUNT|handlers\.generated|FiodosAgent/);
});

test('installing loads no headless browser', () => {
  // jsdom is for the analysis path's real-effect probe. An install that pulled
  // it in would pay a second of startup, and a deprecation warning from a
  // dependency of it, for something it never uses.
  const loaded = () => Object.keys(require.cache).some((p) => p.includes(`${path.sep}jsdom${path.sep}`));

  require('../src/installOrb');
  require('../src/index.js');

  assert.strictEqual(loaded(), false);
});

// ── Asking the backend what the orb knows, without ever depending on it ─────

async function withFetch(impl, work) {
  const real = global.fetch;
  global.fetch = impl;
  try {
    return await work();
  } finally {
    global.fetch = real;
  }
}

test('the manifest is read with the key it was given, from the orb’s own endpoint', async () => {
  const { fetchOrbCapability } = require('../src/index.js');
  const calls = [];

  const capability = await withFetch(
    async (url, opts) => {
      calls.push({ url, opts });
      return { ok: true, status: 200, json: async () => ({ manifest: MANIFEST }) };
    },
    () => fetchOrbCapability({ apiKey: 'fyd_test', apiUrl: 'https://api.example.test' }),
  );

  assert.strictEqual(calls[0].url, 'https://api.example.test/v1/client/manifest');
  assert.strictEqual(calls[0].opts.headers['x-api-key'], 'fyd_test');
  assert.strictEqual(capability.summary.actionCount, 4);
});

test('a backend that cannot be reached comes back as a reason to print', async () => {
  const { fetchOrbCapability } = require('../src/index.js');

  const capability = await withFetch(
    async () => {
      throw new Error('ECONNREFUSED');
    },
    () => fetchOrbCapability({ apiKey: 'fyd_test', apiUrl: 'https://api.example.test' }),
  );

  assert.match(capability.unavailable, /api\.example\.test/);
  assert.strictEqual('summary' in capability, false);
});

test('a project with no analysis is not confused with a backend that failed', async () => {
  // Two different things to say: "you have not analysed yet" is the developer's
  // next step; "we could not ask" is ours. One report line for both would send
  // somebody to run an analysis they already ran.
  const { fetchOrbCapability } = require('../src/index.js');

  const published = await withFetch(
    async () => ({ ok: true, status: 200, json: async () => ({ manifest: null }) }),
    () => fetchOrbCapability({ apiKey: 'fyd_test', apiUrl: 'https://api.example.test' }),
  );
  const refused = await withFetch(
    async () => ({ ok: false, status: 500, json: async () => ({}) }),
    () => fetchOrbCapability({ apiKey: 'fyd_test', apiUrl: 'https://api.example.test' }),
  );

  assert.strictEqual(published.summary, null);
  assert.match(refused.unavailable, /500/);
});

test('an app that already carries an orb is recognised as such', () => {
  const root = writeApp(scratch('already'), {
    'package.json': JSON.stringify({ devDependencies: { vite: '^5' } }),
    'index.html': HTML,
  });
  const plan = planInstall(root);
  assert.strictEqual(isAlreadyInstalled(root, plan), false);

  applyInstall(root, plan, PAYLOAD);

  assert.strictEqual(isAlreadyInstalled(root, plan), true);
});
