'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { restoreDroppedActions, extractBridgeRegistrations } = require('../src/continuityFloor');

// Regression (17/07/2026): a dashboard re-analysis silently omitted the
// landing actions (go_to_login / go_to_signup / log_in_with_credentials)
// although their code and generated FYODOS:BRIDGE registrations were intact;
// the wiring step then deleted the orphaned bridges and voice login died.
// The continuity floor restores such actions — and ONLY such actions.

const BRIDGED_COMPONENT = `import { useState } from 'react';
// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)
/* eslint-disable */
import { registerFiodosBridge } from '../fyodos/bridge';
/* eslint-enable */
// FYODOS:BRIDGE:END

export function PublicScreens() {
  const [screen, setScreen] = useState('landing');
  // FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)
  /* eslint-disable */
  registerFiodosBridge({
    "go_to_login": () => (setScreen('login')),
    "go_to_signup": () => (setScreen('signup')),
  });
  /* eslint-enable */
  // FYODOS:BRIDGE:END
  return null;
}
`;

function prevAction(intent, handler) {
  return {
    intent,
    label: intent,
    category: 'navigation',
    handler,
    requireConfirmation: false,
    parameters: {},
    examples: [intent],
  };
}

function makeRepo() {
  const appRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-floor-'));
  fs.mkdirSync(path.join(appRoot, 'src/pages'), { recursive: true });
  fs.writeFileSync(path.join(appRoot, 'src/pages/PublicScreens.tsx'), BRIDGED_COMPONENT);
  return appRoot;
}

test('extractBridgeRegistrations indexes generated bridge entries', () => {
  const appRoot = makeRepo();
  try {
    const regs = extractBridgeRegistrations(appRoot);
    assert.equal(regs.get('go_to_login').invoke, "setScreen('login')");
    assert.equal(regs.get('go_to_login').file, 'src/pages/PublicScreens.tsx');
    assert.ok(regs.has('go_to_signup'));
  } finally {
    fs.rmSync(appRoot, { recursive: true, force: true });
  }
});

test('a dropped action still bridged in the repo is restored with synthesized wiring', () => {
  const appRoot = makeRepo();
  try {
    const manifest = { actions: [prevAction('publish_changes', 'publishChanges')] };
    const wiring = {};
    const provenance = { actions: [] };
    const previousManifest = {
      actions: [
        prevAction('publish_changes', 'publishChanges'),
        prevAction('go_to_login', 'setScreen'),
      ],
    };
    const restored = restoreDroppedActions({ manifest, wiring, provenance, previousManifest, appRoot });
    assert.deepEqual(restored, ['go_to_login']);
    assert.equal(manifest.actions.length, 2);
    assert.equal(wiring.go_to_login.strategy, 'bridge');
    assert.equal(wiring.go_to_login.bridge.file, 'src/pages/PublicScreens.tsx');
    assert.equal(wiring.go_to_login.bridge.invoke, "setScreen('login')");
    const prov = provenance.actions.find((a) => a.intent === 'go_to_login');
    assert.equal(prov.included, true);
    assert.match(prov.verification, /continuity floor/);
  } finally {
    fs.rmSync(appRoot, { recursive: true, force: true });
  }
});

test('a dropped action with no remaining bridge registration stays dropped', () => {
  const appRoot = makeRepo();
  try {
    const manifest = { actions: [] };
    const provenance = { actions: [] };
    const previousManifest = { actions: [prevAction('removed_feature', 'removedHandler')] };
    const restored = restoreDroppedActions({ manifest, wiring: {}, provenance, previousManifest, appRoot });
    assert.deepEqual(restored, []);
    assert.equal(manifest.actions.length, 0);
  } finally {
    fs.rmSync(appRoot, { recursive: true, force: true });
  }
});

test('a probable rename (same handler under a new intent) is NOT restored', () => {
  const appRoot = makeRepo();
  try {
    // New manifest renamed go_to_login → open_login but kept the handler; the
    // backend reconciliation maps the id back — restoring would duplicate it.
    const manifest = { actions: [prevAction('open_login', 'setScreen')] };
    const provenance = { actions: [] };
    const previousManifest = { actions: [prevAction('go_to_login', 'setScreen')] };
    const restored = restoreDroppedActions({ manifest, wiring: {}, provenance, previousManifest, appRoot });
    assert.deepEqual(restored, []);
    assert.equal(manifest.actions.length, 1);
  } finally {
    fs.rmSync(appRoot, { recursive: true, force: true });
  }
});
