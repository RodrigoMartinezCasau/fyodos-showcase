/**
 * Regression tests for the two wiring guarantees that fix the
 * "promises an action, then silently does nothing" failure class:
 *
 * 1) PARAMETER CONTRACT (checkParamContract): a wiring expression may only
 *    read `args.<name>` / `params.<name>` values that the manifest declares
 *    for that action. Anything else is ALWAYS undefined at runtime and
 *    compiles clean — the select_voice_mode production bug (invoke read
 *    args.voiceMode while the manifest declared 'mode'; every call fell back
 *    to a default and reported a false success).
 *
 * 2) STALE-BLOCK SWEEP (sweepStaleGeneratedBlocks): when a re-analysis moves
 *    an action's wiring to a different component, the previous component's
 *    GENERATED FYODOS:BRIDGE block must be removed — otherwise two components
 *    register the same key with different argument contracts and whichever
 *    mounts last silently wins. Developer-authored blocks survive.
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const {
  checkParamContract,
  sweepStaleGeneratedBlocks,
  stripFiodosBlocks,
} = require('../src/wireHandlers');

// ── 1) Parameter contract ──────────────────────────────────────────────────────

test('checkParamContract rejects an args.<name> the manifest does not declare', () => {
  const res = checkParamContract(
    "(args) => patchWorkspace({ voiceMode: args.voiceMode === 'device' ? 'device' : 'premium' })",
    'args',
    [{ name: 'mode', required: true }],
  );
  assert.strictEqual(res.ok, false);
  assert.match(res.reason, /args\.voiceMode/);
  assert.match(res.reason, /'mode'/);
});

test('checkParamContract accepts declared names (dot and bracket access)', () => {
  const ok1 = checkParamContract(
    '(args) => patchWorkspace({ voiceMode: args.mode })',
    'args',
    [{ name: 'mode', required: true }],
  );
  assert.strictEqual(ok1.ok, true);

  const ok2 = checkParamContract(
    "(args) => setLang(args['lang'])",
    'args',
    [{ name: 'lang', required: true }],
  );
  assert.strictEqual(ok2.ok, true);
});

test('checkParamContract rejects any param read when the action declares none', () => {
  const res = checkParamContract('(args) => doIt(args.value)', 'args', []);
  assert.strictEqual(res.ok, false);
  assert.match(res.reason, /NO parameters/);
});

test('checkParamContract also covers the module strategy receiver (params)', () => {
  const bad = checkParamContract("addItem(params['title'], params.qty)", 'params', [
    { name: 'title', required: true },
  ]);
  assert.strictEqual(bad.ok, false);
  assert.match(bad.reason, /params\.qty/);
});

test('checkParamContract ignores other identifiers and non-param property chains', () => {
  const res = checkParamContract(
    '(args) => store.settings.update({ mode: args.mode })',
    'args',
    [{ name: 'mode', required: true }],
  );
  assert.strictEqual(res.ok, true);
});

// ── 2) Stale generated block sweep ─────────────────────────────────────────────

const GENERATED_BLOCK = [
  '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)',
  '/* eslint-disable */',
  'registerFiodosBridge({',
  '  "select_voice_mode": (args) => (patchWorkspace({ voiceMode: args.mode })),',
  '});',
  '/* eslint-enable */',
  '// FYODOS:BRIDGE:END',
].join('\n');

const DEVELOPER_BLOCK = [
  '// FYODOS:BRIDGE:START (manual wiring — logout)',
  "registerFiodosBridge({ logout: () => doLogout() });",
  '// FYODOS:BRIDGE:END',
].join('\n');

function makeApp() {
  const appRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-sweep-'));
  fs.mkdirSync(path.join(appRoot, 'src/components'), { recursive: true });
  return appRoot;
}

test('sweepStaleGeneratedBlocks removes generated blocks from files NOT wired this run', () => {
  const appRoot = makeApp();
  const staleRel = 'src/components/OldHost.tsx';
  const freshRel = 'src/components/NewHost.tsx';
  fs.writeFileSync(
    path.join(appRoot, staleRel),
    `export function OldHost() {\n${GENERATED_BLOCK}\n  return null;\n}\n`,
  );
  fs.writeFileSync(
    path.join(appRoot, freshRel),
    `export function NewHost() {\n${GENERATED_BLOCK}\n  return null;\n}\n`,
  );

  const files = [
    { rel: staleRel, content: '' },
    { rel: freshRel, content: '' },
  ];
  const backups = sweepStaleGeneratedBlocks(appRoot, files, [freshRel]);

  const stale = fs.readFileSync(path.join(appRoot, staleRel), 'utf8');
  const fresh = fs.readFileSync(path.join(appRoot, freshRel), 'utf8');
  assert.ok(!stale.includes('FYODOS:BRIDGE:START'), 'stale generated block must be swept');
  assert.ok(fresh.includes('FYODOS:BRIDGE:START'), 'the file wired THIS run is untouched');
  assert.strictEqual(backups.length, 1);
  assert.strictEqual(backups[0].file, staleRel);
  assert.ok(backups[0].original.includes('FYODOS:BRIDGE:START'), 'backup carries the original for revert');
});

test('sweepStaleGeneratedBlocks preserves developer-authored FYODOS:BRIDGE blocks', () => {
  const appRoot = makeApp();
  const rel = 'src/components/Manual.tsx';
  fs.writeFileSync(
    path.join(appRoot, rel),
    `export function Manual() {\n${DEVELOPER_BLOCK}\n  return null;\n}\n`,
  );
  const backups = sweepStaleGeneratedBlocks(appRoot, [{ rel, content: '' }], []);
  const after = fs.readFileSync(path.join(appRoot, rel), 'utf8');
  assert.ok(after.includes('manual wiring — logout'), 'developer block must survive verbatim');
  assert.strictEqual(backups.length, 0, 'nothing swept → nothing to back up');
});

test('sweepStaleGeneratedBlocks is a no-op on files without markers and on missing files', () => {
  const appRoot = makeApp();
  const rel = 'src/components/Clean.tsx';
  fs.writeFileSync(path.join(appRoot, rel), 'export const Clean = () => null;\n');
  const backups = sweepStaleGeneratedBlocks(
    appRoot,
    [{ rel, content: '' }, { rel: 'src/ghost.tsx', content: '' }],
    [],
  );
  assert.strictEqual(backups.length, 0);
  assert.strictEqual(
    fs.readFileSync(path.join(appRoot, rel), 'utf8'),
    'export const Clean = () => null;\n',
  );
});

test('stripFiodosBlocks (used by the sweep) removes generated but keeps developer blocks in one file', () => {
  const src = `a();\n${GENERATED_BLOCK}\nb();\n${DEVELOPER_BLOCK}\nc();\n`;
  const out = stripFiodosBlocks(src);
  assert.ok(!out.includes('generated by Fiodos'), 'generated block gone');
  assert.ok(out.includes('manual wiring — logout'), 'developer block kept');
});
