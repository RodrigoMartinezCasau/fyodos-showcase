/**
 * insertImportBlock must treat a MULTI-LINE import as one statement.
 *
 * Regression: the per-line matcher saw `import {` and inserted the generated
 * import in the middle of the open brace list, corrupting the host file
 * (TS1003 "Identifier expected") — which then failed the wiring of EVERY
 * action anchored in that file (the exact AssistantSection.tsx failure).
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { insertImportBlock } = require('../src/wireHandlers');

const GEN = "import { fyodosRegisterHandler } from './fyodos/registry';";

test('inserts after a trailing multi-line import, never inside it', () => {
  const src = [
    "import { useEffect } from 'react';",
    'import {',
    '  prepareLogoForMobileUpload,',
    '  UnsupportedLogoFormatError,',
    "} from '@/lib/normalizeLogoUpload';",
    '',
    'export function AssistantSection() {}',
    '',
  ].join('\n');

  const out = insertImportBlock(src, GEN);
  const lines = out.split('\n');
  assert.strictEqual(lines[5], GEN, 'generated import must follow the closing `} from …` line');
  // The multi-line import must remain intact and contiguous.
  assert.ok(out.includes("import {\n  prepareLogoForMobileUpload,\n  UnsupportedLogoFormatError,\n} from '@/lib/normalizeLogoUpload';"));
});

test('single-line imports still get the block after the last one', () => {
  const src = ["import a from 'a';", "import b from 'b';", '', 'const x = 1;', ''].join('\n');
  const out = insertImportBlock(src, GEN);
  assert.strictEqual(out.split('\n')[2], GEN);
});

test('files with no imports get the block at the top', () => {
  const out = insertImportBlock('const x = 1;\n', GEN);
  assert.ok(out.startsWith(GEN));
});

test('never inserts after an import that lives inside a FYODOS:* marker block', () => {
  // Exact install failure mode: handlers already wrote a BRIDGE import; screen
  // then called insertImportBlock and nested a second import INSIDE BRIDGE,
  // redeclaring registerFiodosBridge (Vite/Babel compile break).
  const src = [
    "import { useState } from 'react';",
    '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)',
    '/* eslint-disable */',
    "import { registerFiodosBridge } from './fyodos/bridge';",
    '/* eslint-enable */',
    '// FYODOS:BRIDGE:END',
    '',
    'export function App() { return null; }',
    '',
  ].join('\n');
  const screenImport = [
    '// FYODOS:SCREEN:START (generated by Fiodos — safe to remove)',
    '/* eslint-disable */',
    "import { registerFiodosBridge } from './fyodos/bridge';",
    '/* eslint-enable */',
    '// FYODOS:SCREEN:END',
  ].join('\n');

  const out = insertImportBlock(src, screenImport);
  assert.ok(
    !/FYODOS:BRIDGE:START[\s\S]*FYODOS:SCREEN:START[\s\S]*FYODOS:BRIDGE:END/.test(out),
    'SCREEN block must not nest inside BRIDGE',
  );
  // Inserted after the host import, before the BRIDGE block.
  const hostIdx = out.indexOf("import { useState } from 'react';");
  const screenIdx = out.indexOf('FYODOS:SCREEN:START');
  const bridgeIdx = out.indexOf('FYODOS:BRIDGE:START');
  assert.ok(hostIdx >= 0 && screenIdx > hostIdx && screenIdx < bridgeIdx);
});

test('empty import block is a no-op', () => {
  const src = "import a from 'a';\n";
  assert.strictEqual(insertImportBlock(src, ''), src);
  assert.strictEqual(insertImportBlock(src, '   \n'), src);
});
