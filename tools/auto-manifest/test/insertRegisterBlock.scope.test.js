/**
 * insertRegisterBlock must NEVER drop the registration inside a NESTED
 * function body.
 *
 * Regression (Fiodos dashboard, production): the anchor resolved to a bare
 * call statement (`patchOrbTheme({...});`) that lives INSIDE an event-handler
 * closure (`const pickCustomWaveformColor = (hex) => { ... }`). The
 * statement-placement branch inserted registerFiodosBridge right after it —
 * compiles, verifies, but the registration only runs if the user manually
 * picks a waveform color. Every orb-design action then failed at runtime with
 * FYODOS_HANDLER_UNREADY ("No he podido hacerlo. Inténtalo de nuevo.").
 *
 * The scope guard compares brace depth of the candidate statement vs the
 * component's JSX return: deeper → fall back to the top-level return spot.
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { insertRegisterBlock } = require('../src/wireHandlers');

const BLOCK = [
  '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)',
  'registerFiodosBridge({ "change_orb_color": (args) => (pickCustomColor(args.color)) });',
  '// FYODOS:BRIDGE:END',
].join('\n');

test('statement anchor inside a nested closure falls back to the component top level', () => {
  const src = [
    'export function AssistantSection() {',
    '  const { patchOrbTheme } = useApp();',
    '  const pickCustomColor = (hex) => {',
    "    patchOrbTheme({ colorKey: 'custom', accentColor: hex });",
    '  };',
    '  const pickCustomWaveformColor = (hex) => {',
    '    enterWaveformPreview();',
    "    patchOrbTheme({ waveformColorKey: 'custom', waveformColor: normalizeHex(hex) });",
    '  };',
    '  return (',
    '    <div>panel</div>',
    '  );',
    '}',
    '',
  ].join('\n');

  // The anchor is the bare call INSIDE pickCustomWaveformColor (statement line).
  const anchor = "    patchOrbTheme({ waveformColorKey: 'custom', waveformColor: normalizeHex(hex) });";
  const out = insertRegisterBlock(src, 'src/AssistantSection.tsx', anchor, BLOCK, 'statement');

  const regIdx = out.indexOf('registerFiodosBridge(');
  const returnIdx = out.indexOf('return (');
  const closureEnd = out.indexOf('};', out.indexOf('pickCustomWaveformColor'));
  assert.ok(regIdx !== -1, 'block inserted');
  assert.ok(
    regIdx > closureEnd,
    'registration must NOT land inside the nested closure body',
  );
  assert.ok(regIdx < returnIdx, 'registration sits before the component JSX return');
});

test('statement anchor at the component top level keeps the after-statement placement', () => {
  const src = [
    'export function SettingsSection() {',
    '  const { redeemPromo } = useApp();',
    '  const currentPlanLabel = resolvePlanDisplayName(usageSummary?.planId);',
    '  if (loading) {',
    '    return <Spinner />;',
    '  }',
    '  return (',
    '    <div>settings</div>',
    '  );',
    '}',
    '',
  ].join('\n');

  // Top-level declaration statement: insert right after it (never snapped into
  // the conditional early-return branch).
  const anchor = '  const currentPlanLabel = resolvePlanDisplayName(usageSummary?.planId);';
  const out = insertRegisterBlock(src, 'src/SettingsSection.tsx', anchor, BLOCK, 'statement');

  const regIdx = out.indexOf('registerFiodosBridge(');
  const ifIdx = out.indexOf('if (loading)');
  assert.ok(regIdx !== -1 && regIdx < ifIdx, 'kept the immediate after-statement placement');
});
