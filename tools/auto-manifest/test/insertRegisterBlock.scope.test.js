/**
 * insertRegisterBlock must NEVER drop the registration inside a NESTED
 * function body.
 *
 * Regression (Fiodos dashboard, production): the anchor resolved to a bare
 * call statement (`patchOrbTheme({...});`) that lives INSIDE an event-handler
 * closure (`const pickCustomWaveformColor = (hex) => { ... }`). The
 * statement-placement branch inserted registerFiodosBridge right after it —
 * compiles, verifies, but the registration only runs if the user manually
 * picks a waveform color. Every orb-design action then failed at runtime with
 * FYODOS_HANDLER_UNREADY ("No he podido hacerlo. Inténtalo de nuevo.").
 *
 * The scope guard compares brace depth of the candidate statement vs the
 * component's JSX return: deeper → fall back to the top-level return spot.
 */
'use strict';

const test = require('node:test');
const assert = require('node:assert');
const { insertRegisterBlock } = require('../src/wireHandlers');

const BLOCK = [
  '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)',
  'registerFiodosBridge({ "change_orb_color": (args) => (pickCustomColor(args.color)) });',
  '// FYODOS:BRIDGE:END',
].join('\n');

test('statement anchor inside a nested closure falls back to the component top level', () => {
  const src = [
    'export function AssistantSection() {',
    '  const { patchOrbTheme } = useApp();',
    '  const pickCustomColor = (hex) => {',
    "    patchOrbTheme({ colorKey: 'custom', accentColor: hex });",
    '  };',
    '  const pickCustomWaveformColor = (hex) => {',
    '    enterWaveformPreview();',
    "    patchOrbTheme({ waveformColorKey: 'custom', waveformColor: normalizeHex(hex) });",
    '  };',
    '  return (',
    '    <div>panel</div>',
    '  );',
    '}',
    '',
  ].join('\n');

  // The anchor is the bare call INSIDE pickCustomWaveformColor (statement line).
  const anchor = "    patchOrbTheme({ waveformColorKey: 'custom', waveformColor: normalizeHex(hex) });";
  const out = insertRegisterBlock(src, 'src/AssistantSection.tsx', anchor, BLOCK, 'statement');

  const regIdx = out.indexOf('registerFiodosBridge(');
  const returnIdx = out.indexOf('return (');
  const closureEnd = out.indexOf('};', out.indexOf('pickCustomWaveformColor'));
  assert.ok(regIdx !== -1, 'block inserted');
  assert.ok(
    regIdx > closureEnd,
    'registration must NOT land inside the nested closure body',
  );
  assert.ok(regIdx < returnIdx, 'registration sits before the component JSX return');
});

/**
 * A file holding several components: the registration must land in the body the
 * anchor belongs to, never in a neighbour's.
 *
 * Regression (Fiodos dashboard, OwnServiceConnectCard.tsx): placement snapped to
 * the JSX return closest IN CHARACTERS, which belonged to a small presentational
 * component declared above the real one. The block compiled as text but read
 * `token`, `clientId`, `onDisconnect` and `onAnalyze` — all declared in the other
 * component — so the project failed with four "Cannot find name" errors. Because
 * the whole file's actions share one block, one misplacement drops them all.
 */
test('with several components in one file the block stays in the anchor own body', () => {
  const pad = (n, what) => Array.from({ length: n }, (_, i) => `  const ${what}${i} = ${i};`);
  const src = [
    "import { useApp } from '../context/AppProvider';",
    '',
    'function labelOf(row, provider) {',
    '  return (',
    '    row?.name || provider',
    '  );',
    '}',
    '',
    'export function OwnServiceConnectCard() {',
    '  const { session } = useApp();',
    "  const token = session?.token || '';",
    '  const internal = useInternalProject();',
    '  if (!internal) return null;',
    ...pad(40, 'row'),
    '  const onDisconnect = async (provider) => {',
    '    await disconnectInternalService(token, provider);',
    '  };',
    ...pad(40, 'more'),
    '  return (',
    '    <section>card</section>',
    '  );',
    '}',
    '',
  ].join('\n');

  const block = [
    '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)',
    'registerFiodosBridge({ "disconnect_service": (args) => (onDisconnect(args.provider)) });',
    '// FYODOS:BRIDGE:END',
  ].join('\n');

  // The real anchor from the dashboard analysis: an early-return guard, which is
  // not a plain statement line, so placement falls through to the JSX return.
  const anchor = '  if (!internal) return null;';
  const out = insertRegisterBlock(src, 'src/OwnServiceConnectCard.tsx', anchor, block, 'statement');

  const regIdx = out.indexOf('registerFiodosBridge(');
  assert.ok(regIdx !== -1, 'block inserted');
  assert.ok(
    regIdx > out.indexOf('export function OwnServiceConnectCard'),
    'the block must not land in the neighbouring helper, whose return is closer',
  );
  assert.ok(
    regIdx > out.indexOf('const onDisconnect'),
    'it belongs at the component top level, where the handlers it calls are in scope',
  );
  assert.ok(regIdx < out.indexOf('<section>card</section>'), 'and before that component JSX return');
});

/**
 * A declaration anchor whose statement SPANS lines must never be cut open.
 *
 * Regression (Fiodos dashboard, TeamInvitationsPanel.tsx): the derived anchor
 * was `const onRevoke = useCallback(` and the block landed on the next line —
 * inside the call's argument list — producing `TS1005: ')' expected` and taking
 * every action of that file down with it. Placement used to count braces to
 * find the component's own return, and an apostrophe in a comment ("don't")
 * reads as a string opener that swallows code, so the count drifted and the
 * real return went unrecognised. The parser is not fooled by prose.
 */
test('an anchor that opens a multi-line call is never split', () => {
  const src = [
    'export function TeamInvitationsPanel() {',
    '  const { token } = useApp();',
    "  // We don't refresh here: the caller already did.",
    '  const onRevoke = useCallback(',
    '    async (inviteId) => {',
    '      await revokeInvite(token, inviteId);',
    '    },',
    '    [token],',
    '  );',
    '  return (',
    '    <div>team</div>',
    '  );',
    '}',
    '',
  ].join('\n');

  const block = [
    '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)',
    'registerFiodosBridge({ "revoke_team_invitation": (args) => (onRevoke(String(args.inviteId))) });',
    '// FYODOS:BRIDGE:END',
  ].join('\n');

  const anchor = '  const onRevoke = useCallback(';
  const out = insertRegisterBlock(src, 'src/TeamInvitationsPanel.tsx', anchor, block, 'statement');

  const regIdx = out.indexOf('registerFiodosBridge(');
  assert.ok(regIdx !== -1, 'block inserted');
  assert.ok(
    regIdx > out.indexOf('[token],'),
    'the block must land after the whole useCallback statement, never inside its arguments',
  );
  assert.ok(regIdx < out.indexOf('<div>team</div>'), 'and before the component JSX return');
});

test('statement anchor at the component top level keeps the after-statement placement', () => {
  const src = [
    'export function SettingsSection() {',
    '  const { redeemPromo } = useApp();',
    '  const currentPlanLabel = resolvePlanDisplayName(usageSummary?.planId);',
    '  if (loading) {',
    '    return <Spinner />;',
    '  }',
    '  return (',
    '    <div>settings</div>',
    '  );',
    '}',
    '',
  ].join('\n');

  // Top-level declaration statement: insert right after it (never snapped into
  // the conditional early-return branch).
  const anchor = '  const currentPlanLabel = resolvePlanDisplayName(usageSummary?.planId);';
  const out = insertRegisterBlock(src, 'src/SettingsSection.tsx', anchor, BLOCK, 'statement');

  const regIdx = out.indexOf('registerFiodosBridge(');
  const ifIdx = out.indexOf('if (loading)');
  assert.ok(regIdx !== -1 && regIdx < ifIdx, 'kept the immediate after-statement placement');
});
