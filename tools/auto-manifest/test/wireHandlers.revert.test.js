/**
 * Regression tests for the REVERT CONTRACT of the handler wiring.
 *
 * The failure these fix: on a RE-ANALYSIS (any second run) the generated modules
 * `fyodos/handlers.generated.*` and `fyodos/bridge.*` already exist from the
 * earlier install, and the developer's own files still import them. When the new
 * wiring failed the build, the revert restored the developer's files to their
 * pre-run content but DELETED both modules — leaving the repo in a state that
 * never existed: imports pointing at nothing. Nothing fails locally (the CLI is
 * already done); it fails in the developer's next build, on their CI/host, with
 * "Cannot find module '../fyodos/bridge'". The analysis had succeeded and the
 * manifest was published, so the report read like a clean skip.
 *
 * The contract asserted here:
 *   1) a revert restores the pre-run state EXACTLY — including generated modules
 *      that existed before this run (snapshot + restore, never delete),
 *   2) a first install still leaves nothing behind (created modules ARE deleted),
 *   3) a generated module that any surviving file still imports is never deleted,
 *   4) a revert is PROVEN with a build, and when the project still does not
 *      build the report says so instead of claiming the code was left untouched.
 *
 * Usage: node --test test/wireHandlers.revert.test.js
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const {
  wireHandlers,
  reportHandlerResult,
  revertAll,
  buildBridgeModule,
  EDIT_START,
  EDIT_END,
} = require('../src/wireHandlers');

function write(p, content) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
}

const COMPONENT_REL = 'src/components/App.tsx';
const MOUNT_REL = 'src/main.tsx';
const PRIOR_REGISTRY_MARK = 'PRIOR-INSTALL-REGISTRY';

/**
 * A project as a SECOND run finds it: the previous install already wrote the
 * bridge + registry, edited the component (generated block + import) and
 * connected the registry to the mounted orb in the entry file.
 */
function scaffoldReinstalledApp({ priorModules = true } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-revert-'));
  write(path.join(root, 'package.json'), JSON.stringify({ name: 'tmp', type: 'module' }));
  write(path.join(root, 'tsconfig.json'), '{}');

  const componentSrc =
    `import { useState } from 'react';\n` +
    (priorModules
      ? `${EDIT_START}\nimport { registerFiodosBridge } from '../fyodos/bridge';\n${EDIT_END}\n`
      : '') +
    `\n` +
    `export default function App() {\n` +
    `  const [items, setItems] = useState<string[]>([]);\n` +
    `  function addItem(title: string) { setItems((prev) => [...prev, title]); }\n` +
    (priorModules
      ? `  ${EDIT_START}\n  registerFiodosBridge({ add_item: (args: any) => addItem(args.title) });\n  ${EDIT_END}\n`
      : '') +
    `  return null;\n` +
    `}\n`;
  write(path.join(root, COMPONENT_REL), componentSrc);

  const mountSrc =
    `import { createRoot } from 'react-dom/client';\n` +
    `import App from './App';\n` +
    (priorModules ? `import { fyodosGeneratedRegistries } from './fyodos/handlers.generated';\n` : '') +
    `\ncreateRoot(document.getElementById('root')!).render(<App />);\n`;
  write(path.join(root, MOUNT_REL), mountSrc);

  let priorBridge = null;
  let priorRegistry = null;
  if (priorModules) {
    priorBridge = buildBridgeModule({ ts: true, esm: true });
    priorRegistry =
      `/** GENERATED by Fiodos — handler wiring. ${PRIOR_REGISTRY_MARK} */\n` +
      `import { getFiodosBridge } from './bridge';\n` +
      `export const fyodosGeneratedRegistries = { handlers: {}, idempotencyCheckers: {} };\n` +
      `void getFiodosBridge;\n`;
    write(path.join(root, 'src/fyodos/bridge.ts'), priorBridge);
    write(path.join(root, 'src/fyodos/handlers.generated.ts'), priorRegistry);
  }

  return { root, componentSrc, mountSrc, priorBridge, priorRegistry };
}

function wiringFixture() {
  const manifest = {
    appName: 'revert-fixture',
    actions: [
      {
        intent: 'add_item',
        handler: 'add_item',
        label: 'Add item',
        parameters: { title: { type: 'string', required: true } },
      },
    ],
  };
  const evidence = { actions: { add_item: { file: COMPONENT_REL, symbol: 'addItem' } } };
  const wiring = {
    add_item: {
      strategy: 'bridge',
      bridgeReason: 'state lives in the component closure',
      bridge: {
        file: COMPONENT_REL,
        anchor: '  function addItem(title: string) { setItems((prev) => [...prev, title]); }',
        invoke: 'addItem(args.title)',
      },
      requiredSymbols: [{ name: 'addItem', file: COMPONENT_REL }],
    },
  };
  return { manifest, evidence, wiring };
}

/**
 * Build runner scripted per call: baseline, post-wiring, post-revert. The wiring
 * always "breaks" the build so every test exercises the revert path.
 */
function scriptedRunner(results) {
  const calls = [];
  const runner = async () => {
    const next = results[Math.min(calls.length, results.length - 1)];
    calls.push(next);
    return next;
  };
  runner.calls = calls;
  return runner;
}

const OK = { ok: true, stage: 'build', output: '' };
const FAIL = { ok: false, stage: 'build', output: "error TS2307: Cannot find module './x'" };

async function runFailingWiring(root, runner) {
  const { manifest, evidence, wiring } = wiringFixture();
  return wireHandlers(root, {
    manifest,
    evidence,
    wiring,
    assumeYes: true,
    quiet: true,
    runTest: true,
    testRunner: runner,
    files: [{ rel: COMPONENT_REL }, { rel: MOUNT_REL }],
  });
}

// ── 1) The re-install revert must restore, not delete ──────────────────────────

test('a reverted re-install keeps the generated modules the previous run left', async () => {
  const app = scaffoldReinstalledApp();
  const runner = scriptedRunner([OK, FAIL, OK]);
  const result = await runFailingWiring(app.root, runner);

  assert.strictEqual(result.status, 'reverted');

  const bridgeAbs = path.join(app.root, 'src/fyodos/bridge.ts');
  const registryAbs = path.join(app.root, 'src/fyodos/handlers.generated.ts');
  assert.ok(fs.existsSync(bridgeAbs), 'the bridge from the PREVIOUS install must survive the revert');
  assert.ok(fs.existsSync(registryAbs), 'the registry from the PREVIOUS install must survive the revert');
  assert.strictEqual(
    fs.readFileSync(bridgeAbs, 'utf8'),
    app.priorBridge,
    'the bridge must be restored byte-for-byte, not rewritten',
  );
  assert.strictEqual(
    fs.readFileSync(registryAbs, 'utf8'),
    app.priorRegistry,
    'the registry must be restored byte-for-byte (the previous action set stays wired)',
  );

  assert.strictEqual(
    fs.readFileSync(path.join(app.root, COMPONENT_REL), 'utf8'),
    app.componentSrc,
    'the developer component must be restored byte-for-byte',
  );

  fs.rmSync(app.root, { recursive: true, force: true });
});

test('no surviving file is left importing a module the revert removed', async () => {
  const app = scaffoldReinstalledApp();
  const result = await runFailingWiring(app.root, scriptedRunner([OK, FAIL, OK]));
  assert.strictEqual(result.status, 'reverted');

  // The exact production break: the entry file still imports the registry and a
  // component still imports the bridge. Every such import must resolve on disk.
  for (const rel of [COMPONENT_REL, MOUNT_REL]) {
    const src = fs.readFileSync(path.join(app.root, rel), 'utf8');
    const specifiers = [...src.matchAll(/from\s+'([^']*fyodos\/[^']+)'/g)].map((m) => m[1]);
    for (const spec of specifiers) {
      const resolved = path.resolve(path.dirname(path.join(app.root, rel)), spec);
      const found = ['.ts', '.tsx', '.js', ''].some((ext) => fs.existsSync(resolved + ext));
      assert.ok(found, `${rel} imports '${spec}' but nothing resolves it after the revert`);
    }
  }

  fs.rmSync(app.root, { recursive: true, force: true });
});

// ── 2) A first install still cleans up after itself ────────────────────────────

test('a reverted FIRST install leaves no generated modules behind', async () => {
  const app = scaffoldReinstalledApp({ priorModules: false });
  const result = await runFailingWiring(app.root, scriptedRunner([OK, FAIL, OK]));

  assert.strictEqual(result.status, 'reverted');
  assert.ok(
    !fs.existsSync(path.join(app.root, 'src/fyodos/bridge.ts')),
    'a bridge created by THIS run must be deleted on revert',
  );
  assert.ok(
    !fs.existsSync(path.join(app.root, 'src/fyodos/handlers.generated.ts')),
    'a registry created by THIS run must be deleted on revert',
  );
  assert.strictEqual(
    fs.readFileSync(path.join(app.root, COMPONENT_REL), 'utf8'),
    app.componentSrc,
    'the developer component must be restored byte-for-byte',
  );

  fs.rmSync(app.root, { recursive: true, force: true });
});

// ── 3) revertAll never deletes a module something still imports ────────────────

test('revertAll keeps a generated module that a restored file still imports', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-revert-unit-'));
  const bridgeAbs = path.join(root, 'src/fyodos/bridge.ts');
  const orphanAbs = path.join(root, 'src/fyodos/unused.generated.ts');
  write(bridgeAbs, 'export function registerFiodosBridge() {}\n');
  write(orphanAbs, 'export const nothingUsesThis = 1;\n');

  const componentAbs = path.join(root, COMPONENT_REL);
  const restored = `import { registerFiodosBridge } from '../fyodos/bridge';\nexport default function App() { return null; }\n`;
  write(componentAbs, 'anything');

  revertAll([{ file: COMPONENT_REL, abs: componentAbs, original: restored }], [bridgeAbs, orphanAbs]);

  assert.ok(fs.existsSync(bridgeAbs), 'a module the restored code imports must not be deleted');
  assert.ok(!fs.existsSync(orphanAbs), 'a module nothing references is still cleaned up');

  fs.rmSync(root, { recursive: true, force: true });
});

test('revertAll checks the files on disk too, not only the ones it restored', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-revert-disk-'));
  const registryAbs = path.join(root, 'src/fyodos/handlers.generated.ts');
  write(registryAbs, 'export const fyodosGeneratedRegistries = { handlers: {} };\n');
  // The entry file was wired by an EARLIER pass, so it is not in `backups`.
  write(
    path.join(root, MOUNT_REL),
    `import { fyodosGeneratedRegistries } from './fyodos/handlers.generated';\nvoid fyodosGeneratedRegistries;\n`,
  );

  revertAll([], [registryAbs], { appRoot: root, files: [{ rel: MOUNT_REL }] });

  assert.ok(
    fs.existsSync(registryAbs),
    'the entry file still imports the registry, so deleting it would break the build',
  );

  fs.rmSync(root, { recursive: true, force: true });
});

// The three wiring phases (handlers, session, screen) all delete through the
// same contract, so lock it once: existing modules are restorable, new ones are
// disposable.
test('snapshotGeneratedFiles separates what existed from what this run creates', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-snapshot-'));
  const existing = path.join(root, 'src/fyodos/session.generated.ts');
  const fresh = path.join(root, 'src/fyodos/screen.generated.ts');
  write(existing, 'export const fyodosIsAuthenticated = () => false;\n');

  const { snapshotGeneratedFiles } = require('../src/wireHandlers');
  const { priorBackups, created } = snapshotGeneratedFiles([existing, fresh]);

  assert.deepStrictEqual(created, [fresh], 'only the module that did not exist may be deleted later');
  assert.strictEqual(priorBackups.length, 1);
  assert.strictEqual(priorBackups[0].abs, existing);
  assert.match(priorBackups[0].original, /fyodosIsAuthenticated/, 'the prior content is kept for the restore');

  fs.rmSync(root, { recursive: true, force: true });
});

// ── 4) The revert is proven with a build, and reported honestly ────────────────

test('the revert is verified with a build before it is called a revert', async () => {
  const app = scaffoldReinstalledApp();
  const runner = scriptedRunner([OK, FAIL, OK]);
  const result = await runFailingWiring(app.root, runner);

  assert.strictEqual(result.status, 'reverted');
  assert.strictEqual(runner.calls.length, 3, 'baseline, post-wiring and post-revert builds must all run');
  assert.strictEqual(result.revertVerified, true, 'a green post-revert build must be recorded as proof');

  fs.rmSync(app.root, { recursive: true, force: true });
});

test('when the project still does not build after the revert, the report says so', async () => {
  const app = scaffoldReinstalledApp();
  // Baseline green, wiring breaks it, and the revert does NOT bring it back.
  const result = await runFailingWiring(app.root, scriptedRunner([OK, FAIL, FAIL]));

  assert.strictEqual(result.status, 'reverted');
  assert.strictEqual(result.revertVerified, false, 'a red post-revert build must be recorded');

  const lines = [];
  const realError = console.error;
  console.error = (...args) => lines.push(args.join(' '));
  try {
    reportHandlerResult(result, {}, { quiet: false });
  } finally {
    console.error = realError;
  }
  const said = lines.join('\n');
  assert.ok(
    !/left untouched/i.test(said),
    'it must never claim the code was left untouched when the build is still red',
  );
  assert.match(said, /does not build|still fails|check/i);
  assert.ok(said.includes(COMPONENT_REL), 'the files it touched must be named so they can be inspected');

  fs.rmSync(app.root, { recursive: true, force: true });
});
