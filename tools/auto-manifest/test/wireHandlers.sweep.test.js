/**
 * Regression tests for the SWEEP CONTRACT of the handler wiring.
 *
 * The sweep removes generated FYODOS:BRIDGE blocks from files this run does not
 * wire, so a re-analysis that moves an action to another component cannot leave
 * a duplicate registration behind. It already preserves developer-authored
 * blocks verbatim — and that is precisely where it broke projects:
 *
 *   - it deleted the generated `import { registerFiodosBridge }` while the
 *     developer's own hand-written block (the one our own FYODOS_HANDLERS.md
 *     tells them to write) still called it → "Cannot find name".
 *   - it deleted the only consumer of a binding the host file destructures,
 *     which under `noUnusedLocals` is a hard error → "declared but never read".
 *
 * Either one fails the candidate build. Since the sweep runs on EVERY attempt,
 * including every probe of the convergence search, no subset of actions can
 * ever be green: the run ends with zero actions wired and a full revert, with
 * the developer's project blamed for a break the CLI introduced.
 *
 * The contract asserted here: sweeping never leaves a file referencing
 * something that is gone, and never orphans a binding it was using. A block
 * that cannot be removed safely stays — the file compiled with it a moment ago.
 *
 * Usage: node --test test/wireHandlers.sweep.test.js
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const { sweepStaleGeneratedBlocks } = require('../src/wireHandlers');

const GEN_START = '// FYODOS:BRIDGE:START (generated by Fiodos — safe to remove)';
const DEV_START = '// FYODOS:BRIDGE:START (manual wiring — logout action; safe to remove)';
const END = '// FYODOS:BRIDGE:END';

function scaffold(rel, content) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fyodos-sweep-'));
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
  return { root, abs, files: [{ rel }] };
}

test('the sweep keeps the import a developer block still calls', () => {
  const { root, abs, files } = scaffold(
    'src/pages/Shell.tsx',
    [
      "import { useEffect } from 'react';",
      "import { useApp } from '../context/AppProvider';",
      GEN_START,
      '/* eslint-disable */',
      "import { registerFiodosBridge } from '../fyodos/bridge';",
      '/* eslint-enable */',
      END,
      '',
      'export function Shell() {',
      '  const { logout } = useApp();',
      '',
      DEV_START,
      '  useEffect(() => {',
      '    registerFiodosBridge({ logout: () => logout() });',
      '  }, [logout]);',
      END,
      '',
      '  return null;',
      '}',
      '',
    ].join('\n'),
  );

  sweepStaleGeneratedBlocks(root, files, []);
  const after = fs.readFileSync(abs, 'utf8');

  assert.match(
    after,
    /import \{ registerFiodosBridge \}/,
    'the developer block still calls registerFiodosBridge, so its import cannot be swept',
  );
  assert.match(after, /registerFiodosBridge\(\{ logout/, 'the developer block is preserved verbatim');
});

test('the sweep keeps a block that is the only consumer of a host binding', () => {
  const { root, abs, files } = scaffold(
    'src/pages/Shell.tsx',
    [
      "import { useApp } from '../context/AppProvider';",
      GEN_START,
      '/* eslint-disable */',
      "import { registerFiodosBridge } from '../fyodos/bridge';",
      '/* eslint-enable */',
      END,
      '',
      'export function Shell() {',
      '  const { lang, publishChanges } = useApp();',
      '  return <p>{lang}</p>;',
      GEN_START,
      '  /* eslint-disable */',
      '  registerFiodosBridge({',
      '    "publish_changes": () => (publishChanges()),',
      '  });',
      '  /* eslint-enable */',
      END,
      '}',
      '',
    ].join('\n'),
  );

  sweepStaleGeneratedBlocks(root, files, []);
  const after = fs.readFileSync(abs, 'utf8');

  assert.match(
    after,
    /publishChanges\(\)/,
    'publishChanges is destructured by the host file and used nowhere else: sweeping its only consumer leaves an unused local, which noUnusedLocals rejects',
  );
});

test('the sweep still removes a block nothing depends on', () => {
  const { root, abs, files } = scaffold(
    'src/components/Old.tsx',
    [
      "import { useApp } from '../context/AppProvider';",
      GEN_START,
      '/* eslint-disable */',
      "import { registerFiodosBridge } from '../fyodos/bridge';",
      '/* eslint-enable */',
      END,
      '',
      'export function Old() {',
      '  const { lang } = useApp();',
      GEN_START,
      '  /* eslint-disable */',
      '  registerFiodosBridge({',
      '    "select_voice_mode": (args) => (console.log(args.mode)),',
      '  });',
      '  /* eslint-enable */',
      END,
      '  return <p>{lang}</p>;',
      '}',
      '',
    ].join('\n'),
  );

  const backups = sweepStaleGeneratedBlocks(root, files, []);
  const after = fs.readFileSync(abs, 'utf8');

  assert.equal(backups.length, 1, 'the swept file is backed up so a regression can restore it');
  assert.doesNotMatch(after, /registerFiodosBridge/, 'a stale duplicate registration is still swept away');
  assert.match(after, /const \{ lang \} = useApp\(\);/, 'the host code is untouched');
});

test('a file wired by this run is left to applyComponentEdits', () => {
  const { root, abs, files } = scaffold(
    'src/components/Live.tsx',
    [
      GEN_START,
      "import { registerFiodosBridge } from '../fyodos/bridge';",
      END,
      'export function Live() { return null; }',
      '',
    ].join('\n'),
  );

  const backups = sweepStaleGeneratedBlocks(root, files, ['src/components/Live.tsx']);

  assert.equal(backups.length, 0);
  assert.match(fs.readFileSync(abs, 'utf8'), /registerFiodosBridge/);
});
